<?php
/**
 * Generate the Laravel runtime's workflow-preset catalogue.
 *
 * The WordPress build ships its presets as a static PHP catalogue in
 * addons/pro/includes/class-wp-mcp-ai-pro-workflow-presets.php. The Laravel
 * runtime has no WordPress, so the same catalogue is exported to JSON and
 * loaded by App\Support\WorkflowPresets.
 *
 * Re-run this after editing the WordPress catalogue:
 *
 *   php bin/generate-laravel-workflow-presets.php
 *
 * The output is deterministic (fixed key order, pretty-printed) so a re-run
 * produces a reviewable diff rather than churn.
 *
 * @package NV_oOS
 */

declare( strict_types=1 );

// The catalogue file exits unless ABSPATH is defined, and its entries call
// these two WordPress helpers. Stub them before loading it.
define( 'ABSPATH', __DIR__ );

if ( ! function_exists( '__' ) ) {
	/**
	 * Translation stub — the catalogue is source-language only.
	 *
	 * @param string $text   Text.
	 * @param string $domain Text domain.
	 * @return string
	 */
	function __( $text, $domain = 'default' ) { // phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedFunctionFound
		unset( $domain );
		return $text;
	}
}

if ( ! function_exists( 'sanitize_key' ) ) {
	/**
	 * Key sanitiser stub.
	 *
	 * @param string $key Key.
	 * @return string
	 */
	function sanitize_key( $key ) { // phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedFunctionFound
		return strtolower( preg_replace( '/[^a-z0-9_\-]/i', '', (string) $key ) );
	}
}

$root   = dirname( __DIR__ );
$source = $root . '/addons/pro/includes/class-wp-mcp-ai-pro-workflow-presets.php';
$target = $root . '/docker/laravel/app-skeleton/resources/workflow-presets.json';

if ( ! is_readable( $source ) ) {
	fwrite( STDERR, "Source catalogue not found: {$source}\n" );
	exit( 1 );
}

require_once $source;

if ( ! class_exists( 'WP_MCP_AI_Pro_Workflow_Presets' ) ) {
	fwrite( STDERR, "WP_MCP_AI_Pro_Workflow_Presets did not load.\n" );
	exit( 1 );
}

// WordPress's get_categories() omits two families that presets actually use
// (fnb, gtmetrix). The console falls back to the raw slug, but a label reads
// better, so supply the missing two here.
$categories = WP_MCP_AI_Pro_Workflow_Presets::get_categories();
$categories = array_merge(
	array(
		'fnb'      => 'Food & Beverage Management',
		'gtmetrix' => 'Performance Audits',
	),
	$categories
);

$presets  = WP_MCP_AI_Pro_Workflow_Presets::get_presets();
$exported = array();

foreach ( $presets as $id => $preset ) {
	$exported[ $id ] = array(
		'name'        => (string) ( $preset['name'] ?? '' ),
		'description' => (string) ( $preset['description'] ?? '' ),
		'category'    => (string) ( $preset['category'] ?? '' ),
		'icon'        => (string) ( $preset['icon'] ?? '' ),
		'tags'        => array_values( array_map( 'strval', (array) ( $preset['tags'] ?? array() ) ) ),
		'nodes'       => array_values( (array) ( $preset['nodes'] ?? array() ) ),
		'edges'       => array_values( (array) ( $preset['edges'] ?? array() ) ),
	);
}

ksort( $exported );
ksort( $categories );

$document = array(
	'_comment'       => 'Generated by bin/generate-laravel-workflow-presets.php from the Pro catalogue. Do not edit by hand.',
	'_license'       => 'LicenseRef-Proprietary — this preset data is Pro-licensed content. The loader that reads it (app/Support/WorkflowPresets.php) is MIT, like the rest of the app.',
	'generated_from' => 'addons/pro/includes/class-wp-mcp-ai-pro-workflow-presets.php',
	'categories'     => $categories,
	'presets'        => $exported,
);

$json = wp_json_encode_compat( $document );

if ( false === file_put_contents( $target, $json . "\n" ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- build script.
	fwrite( STDERR, "Could not write {$target}\n" );
	exit( 1 );
}

fwrite( STDOUT, sprintf( "Wrote %d presets to %s\n", count( $exported ), $target ) );

/**
 * Deterministic JSON encoder.
 *
 * @param array<string,mixed> $document Document.
 * @return string
 */
function wp_json_encode_compat( array $document ): string {
	$json = json_encode(
		$document,
		JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
	);

	if ( false === $json ) {
		fwrite( STDERR, 'JSON encode failed: ' . json_last_error_msg() . "\n" );
		exit( 1 );
	}

	return $json;
}

#!/usr/bin/env php
<?php
/**
 * Mirror the Schedule Anything preset catalogue into the Laravel app.
 *
 * The catalogue is a static PHP array in
 * `addons/pro/includes/schedule-anything/class-wp-mcp-ai-pro-schedule-presets.php`.
 * A Laravel deployment does not ship `addons/`, and `lib/` is excluded from
 * wp.org builds, so the catalogue has to be copied rather than shared.
 *
 * The copy is committed, and `--check` makes CI fail when the two trees
 * diverge, so the duplication stays explicit instead of going stale. The
 * source class only touches `apply_filters()` while building the catalogue,
 * so it can be loaded here with a one-function stub instead of WordPress.
 *
 * Usage:
 *   php bin/sync-schedule-presets.php            # write the mirror
 *   php bin/sync-schedule-presets.php --check    # exit 1 if the mirror is stale
 *
 * @package WP_MCP_AI
 */

declare( strict_types=1 );

$root   = dirname( __DIR__ );
$source = $root . '/addons/pro/includes/schedule-anything/class-wp-mcp-ai-pro-schedule-presets.php';
$target = $root . '/docker/laravel/app-skeleton/resources/schedule-presets.json';
$check  = in_array( '--check', array_slice( $argv, 1 ), true );

if ( ! is_file( $source ) ) {
	fwrite( STDERR, "sync-schedule-presets: missing source {$source}\n" );
	exit( 1 );
}

// The class guards on ABSPATH and calls apply_filters() while building the
// catalogue. Nothing else from WordPress is needed for get_catalogue().
if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', $root . '/' );
}

if ( ! function_exists( 'apply_filters' ) ) {
	/**
	 * Stub: the catalogue passes through unchanged.
	 *
	 * @param string $tag   Filter name.
	 * @param mixed  $value Value.
	 * @return mixed
	 */
	function apply_filters( $tag, $value ) {
		return $value;
	}
}

require_once $source;

if ( ! class_exists( 'WP_MCP_AI_SA_Schedule_Presets' ) ) {
	fwrite( STDERR, "sync-schedule-presets: catalogue class did not load\n" );
	exit( 1 );
}

$catalogue = WP_MCP_AI_SA_Schedule_Presets::get_catalogue();

if ( ! is_array( $catalogue ) || array() === $catalogue ) {
	fwrite( STDERR, "sync-schedule-presets: catalogue is empty — refusing to write\n" );
	exit( 1 );
}

$document = array(
	'_comment' => 'Generated by bin/sync-schedule-presets.php from addons/pro/includes/schedule-anything/class-wp-mcp-ai-pro-schedule-presets.php. Do not edit by hand — run the sync script.',
	'presets'  => $catalogue,
);

$json = json_encode( $document, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE );

if ( false === $json ) {
	fwrite( STDERR, "sync-schedule-presets: could not encode the catalogue\n" );
	exit( 1 );
}

$json .= "\n";

$existing = is_file( $target ) ? (string) file_get_contents( $target ) : '';

if ( $check ) {
	if ( $existing !== $json ) {
		fwrite( STDERR, "sync-schedule-presets: mirror is stale — run php bin/sync-schedule-presets.php\n" );
		exit( 1 );
	}

	fwrite( STDOUT, 'sync-schedule-presets: up to date (' . count( $catalogue ) . " presets)\n" );
	exit( 0 );
}

$directory = dirname( $target );

if ( ! is_dir( $directory ) && ! mkdir( $directory, 0775, true ) && ! is_dir( $directory ) ) {
	fwrite( STDERR, "sync-schedule-presets: cannot create {$directory}\n" );
	exit( 1 );
}

if ( false === file_put_contents( $target, $json ) ) {
	fwrite( STDERR, "sync-schedule-presets: cannot write {$target}\n" );
	exit( 1 );
}

fwrite( STDOUT, 'sync-schedule-presets: wrote ' . count( $catalogue ) . " presets to {$target}\n" );

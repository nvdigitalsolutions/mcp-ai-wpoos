#!/usr/bin/env bash
#
# generate-tool-coverage-manifest.sh
#
# Regenerates the per-subsystem tool-class manifest files used by
# bin/find-untested-classes.sh to recognize that the data-driven smoke
# test in tests/test-tool-registry-coverage.php covers every registered
# tool class. The manifests list one file basename per line (e.g.
# "wp-mcp-ai-tool-2fa-setup-assistant"), which is exactly what the
# helper greps for.
#
# Re-run this script whenever a tool class is added, removed or renamed
# under includes/tools/ or addons/pro/includes/tools/.
#
# Usage:
#   bin/generate-tool-coverage-manifest.sh
#
set -e

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

generate_manifest() {
    local source_glob_dir="$1"
    local out_file="$2"
    local label="$3"

    mkdir -p "$(dirname "$out_file")"

    {
        printf '# %s tool-class coverage manifest.\n' "$label"
        printf '# Auto-generated by bin/generate-tool-coverage-manifest.sh — do not edit by hand.\n'
        printf '# One tool class file basename per line. Searched by bin/find-untested-classes.sh\n'
        printf '# to recognize coverage from tests/test-tool-registry-coverage.php (the data-driven\n'
        printf '# smoke test that locks the contract for every registered tool: get_slug(),\n'
        printf '# parameter-schema validity, required_capability resolution, and execute() denial).\n'
        printf '#\n'
        find "$source_glob_dir" -type f -name 'class-*.php' \
            | sed -E 's|.*/class-||; s|\.php$||' \
            | sort -u
    } > "$out_file"

    local count
    count=$(grep -cv '^#' "$out_file" || true)
    printf '✓ %s: %d tool classes → %s\n' "$label" "$count" "$out_file"
}

generate_manifest \
    "includes/tools" \
    "tests/tools/.coverage-manifest.txt" \
    "Base"

generate_manifest \
    "addons/pro/includes/tools" \
    "addons/pro/tests/tools/.coverage-manifest.txt" \
    "Pro"

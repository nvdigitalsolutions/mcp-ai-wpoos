<?php
/**
 * Tests for Pro addon update integrity verification.
 *
 * Covers WP_MCP_AI_Plugin_Updater::verify_pro_installation_integrity() and
 * get_vendor_autoload_files() — the guards that prevent a partially copied
 * Pro vendor tree (missing files referenced by the Composer autoloader) from
 * white-screening the site after an in-place update.
 *
 * @package WP_MCP_AI
 * @author    NV Digital Solutions
 * @copyright Copyright (c) 2025-2026 NV Digital Solutions
 * @license   GPL-3.0-or-later

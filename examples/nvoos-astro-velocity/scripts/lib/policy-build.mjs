// ---------------------------------------------------------------------------
// policy-build.mjs — theme-policy generator core (zero-dep, Proposal 105).
// Shared by scripts/build-policy.mjs (writes), scripts/check-policy.mjs
// (drift gate) and tests/unit/policy-drift.test.ts (emission pin).
//
// Fetches GET {NVOOS_API_BASE}/globals/theme at build and emits
// src/lib/theme/policy.generated.ts. The fetch can NEVER break a build:
// any failure / non-200 / 404 / malformed body falls back to the default
// (auto) doc — the hermetic mirror build must stay hermetic (104 §2.5).
// ---------------------------------------------------------------------------

import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const POLICY_OUT = join(HERE, '..', '..', 'src', 'lib', 'theme', 'policy.generated.ts');

export const DEFAULT_DOC = {
	policy: 'auto',
	contrast: 'auto',
	defaultTheme: 'dark',
	updatedAt: '',
	$extensions: {},
};

const BRAND_SLUG_RE = /^brand:[a-z0-9-]+$/;
const POLICY_VALUES = ['auto', 'light', 'dark'];
const CONTRAST_VALUES = ['auto', 'standard', 'high'];
const DEFAULT_THEME_VALUES = ['light', 'dark'];

/** Lenient parse mirroring src/lib/theme/policy.ts parsePolicyDoc. */
export function parseDoc(json) {
	if (json === null || typeof json !== 'object' || Array.isArray(json)) {
		return { ...DEFAULT_DOC };
	}
	const policy =
		typeof json.policy === 'string' &&
		(POLICY_VALUES.includes(json.policy) || BRAND_SLUG_RE.test(json.policy))
			? json.policy
			: DEFAULT_DOC.policy;
	const contrast = CONTRAST_VALUES.includes(json.contrast) ? json.contrast : DEFAULT_DOC.contrast;
	const defaultTheme = DEFAULT_THEME_VALUES.includes(json.defaultTheme)
		? json.defaultTheme
		: DEFAULT_DOC.defaultTheme;
	const updatedAt = typeof json.updatedAt === 'string' ? json.updatedAt : '';
	return { policy, contrast, defaultTheme, updatedAt, $extensions: {} };
}

/**
 * Fetch the policy doc from the build-time base. Returns the default doc on
 * any failure — the fetch is advisory, never fatal (105 §3).
 *
 * @param {string | undefined} base NVOOS_API_BASE value (may be undefined).
 * @returns {Promise<{ doc: Record<string, unknown>, source: string }>}
 */
export async function fetchPolicyDoc(base) {
	if (!base) {
		return { doc: { ...DEFAULT_DOC }, source: 'no NVOOS_API_BASE at build — the default document' };
	}
	const url = `${base.replace(/\/+$/, '')}/globals/theme`;
	try {
		const res = await fetch(url, {
			headers: { accept: 'application/json' },
			signal: AbortSignal.timeout(5000),
		});
		if (!res.ok) {
			return { doc: { ...DEFAULT_DOC }, source: 'no NVOOS_API_BASE at build — the default document' };
		}
		return { doc: parseDoc(await res.json()), source: `GET ${url}` };
	} catch {
		// Network failure / timeout / malformed JSON — fall back, never fail.
		return { doc: { ...DEFAULT_DOC }, source: 'no NVOOS_API_BASE at build — the default document' };
	}
}

/** Single-quote a value for generated TS (repo lint: quotes → single). */
function tsString(value) {
	return `'${String(value)
		.replace(/\\/g, '\\\\')
		.replace(/'/g, "\\'")
		.replace(/\r/g, '\\r')
		.replace(/\n/g, '\\n')}'`;
}

/** Render policy.generated.ts — tabs + single quotes (the tokens-build.mjs
 *  emission discipline; generated TS under src/ is linted). */
export function renderPolicyDoc(doc, source) {
	const lines = [
		'// Generated by scripts/build-policy.mjs — DO NOT EDIT.',
		`// Source: ${source} (never fails the build).`,
		'',
		"import type { ThemePolicy } from './policy';",
		'',
		'export const generatedPolicyDoc: ThemePolicy = {',
		`\tpolicy: ${tsString(doc.policy)},`,
		`\tcontrast: ${tsString(doc.contrast)},`,
		`\tdefaultTheme: ${tsString(doc.defaultTheme)},`,
		`\tupdatedAt: ${tsString(doc.updatedAt)},`,
		'\t$extensions: {},',
		'} as const;',
		'',
	];
	return lines.join('\n');
}

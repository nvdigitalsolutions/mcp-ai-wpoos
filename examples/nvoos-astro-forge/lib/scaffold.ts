/** `case-studies` → `Case Studies` — the generated listing heading. */
export function collectionTitle( slug: string ): string {
	return slug
		.split( /[-_]+/ )
		.filter( Boolean )
		.map( ( part ) => part.charAt( 0 ).toUpperCase() + part.slice( 1 ) )
		.join( ' ' );
}


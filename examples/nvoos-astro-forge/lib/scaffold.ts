		let hasDesignRenderer = false;
		try {
			await stat( path.join( targetDir, 'src', 'components', 'design', 'DesignRenderer.astro' ) );
			hasDesignRenderer = true;
		} catch {
			// No renderer — nothing to wire into.
		}

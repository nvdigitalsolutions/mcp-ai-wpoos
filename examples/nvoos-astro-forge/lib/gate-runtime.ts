/**
 * @fileoverview Emits the managed tier's front controller and gate modules.
 *
 * Invariant: the gate runs before the static handler and never blocks a visitor
 * on a CMS round trip; the poll happens off the request path. Never renders the
 * holding page's copy — that ships as a prerendered document.
 */
// ---------------------------------------------------------------------------
// gate-runtime.ts — the MANAGED tier's publication gate (Proposal 165 P2/P3).
//
// A forged managed site serves PRERENDERED documents, so Astro middleware never
// sees a request to `/` before the file is found on disk. The artifact
// therefore ships a tiny front controller (`server.js`) that consults this gate
// BEFORE the static handler:
//
//   server.js → forge-gate/runtime.mjs (the gate) → forge-gate/static.mjs
//            → dist/server/entry.mjs (Astro, middleware mode)
//
// The verdict is `gate.generated.json` (written by gate-publish.ts): the BOOT
// state, then polled and pushable. The signed `/manage` session is verified
// LOCALLY here (HMAC over the same `manage.v1.` recipe as manage-session.ts),
// so a manager keeps seeing the real site when the CMS is unreachable — which
// is exactly when a maintenance gate is on.
//
// REBUILD NOTE (2026-11-26): rebuilt after the uncommitted tree was lost. The
// emitted contracts are pinned by `tests/gate-runtime.test.ts`; the constants
// (allowlist, header set, modes, the `manage.v1.` HMAC recipe) are reproduced
// from the surrounding modules and the proposal record.
// ---------------------------------------------------------------------------

import { createReadStream } from 'node:fs';
import { stat } from 'node:fs/promises';
import path from 'node:path';

/**
 * The emitted `forge-gate/runtime.mjs` — the gate itself.
 *
 * Contract:
 *   createGate({ root, targetSite, pushToken, secret, sessionSecret })
 *     → { handle(req, res): Promise<boolean>, close(), state(), bypassUrl(path) }
 *
 * `handle` answers TRUE when it produced the response, FALSE to let the app
 * serve. A bypass or a manager session returns FALSE after setting the preview
 * headers, so the real site is served but never cacheable or indexable.
 */
const SOURCE_STATE = String.raw`// Generated by NV oOS Astro Forge — managed publication gate (Proposal 165).
//
// Reads gate.generated.json at boot (the build-time verdict), polls the CMS's
// bridge route, accepts a signed push, and verifies the /manage session
// locally. Never trusts a cookie's PRESENCE: bypass and session tokens are
// both HMAC-verified with timingSafeEqual.

import { createHmac, randomBytes, timingSafeEqual } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const MODES = new Set(['off', 'maintenance', 'coming_soon']);
const DEFAULT_ALLOW = [
	'/api/',
	'/_astro/',
	'/manage',
	'/manage-assets/',
	'/media/',
	'/robots.txt',
	'/sitemap.xml',
	'/feed.xml',
	'/favicon.ico',
	'/.well-known/',
];

function positive(value, fallback) {
	const number = Number(value);
	return Number.isFinite(number) && number > 0 ? number : fallback;
}

function validMode(value) {
	const mode = String(value ?? '').trim().toLowerCase().replace(/-/g, '_');
	return MODES.has(mode) ? mode : 'off';
}

function safeEqual(left, right) {
	const a = Buffer.from(String(left ?? ''));
	const b = Buffer.from(String(right ?? ''));
	return a.length === b.length && timingSafeEqual(a, b);
}

function cookieValue(req, name) {
	const header = String(req.headers.cookie ?? '');
	if (!header) {
		return '';
	}
	for (const part of header.split(';')) {
		const index = part.indexOf('=');
		if (index === -1) {
			continue;
		}
		if (part.slice(0, index).trim() === name) {
			return part.slice(index + 1).trim();
		}
	}
	return '';
}

function readBody(req) {
	return new Promise((resolve) => {
		let body = '';
		req.on('data', (chunk) => {
			body += chunk;
			if (body.length > 64 * 1024) {
				req.destroy();
			}
		});
		req.on('end', () => resolve(body));
		req.on('error', () => resolve(''));
	});
}

function provisionSecret(root) {
	// Only a scaffolded app provisions. A unit test or a bare consumer with no
	// gate manifest must keep failing closed.
	if (!existsSync(join(root, 'gate.generated.json'))) {
		return '';
	}
	const path = join(root, '.forge-gate-secret');
	const read = () => {
		try {
			return String(readFileSync(path, 'utf8')).trim();
		} catch {
			return '';
		}
	};
	const existing = read();
	if (existing) {
		return existing;
	}
	const generated = randomBytes(32).toString('hex');
	try {
		writeFileSync(path, generated + '\n', { mode: 0o600, flag: 'wx' });
		return generated;
	} catch {
		const raced = read();
		if (raced) {
			return raced;
		}
		console.warn('[forge-gate] no signing secret configured and ' + path + ' is not writable; sessions and bypass links reset on restart.');
		return generated;
	}
}

export function createGate(options = {}) {
	const root = options.root ?? process.cwd();
	const targetSite = String(options.targetSite ?? process.env.NVOOS_TARGET_SITE ?? '').replace(/\/+$/, '');
	const pushToken = String(options.pushToken ?? process.env.NVOOS_REVALIDATE_TOKEN ?? '');
	// A key must exist even when the operator set none: the /manage session and
	// the bypass token both depend on it, and a missing key made sign-in refuse
	// with error=config. Provision one ONCE beside the app; the env still wins.
	const secret = String(options.secret ?? '').trim() || String(process.env.NVOOS_FORGE_GATE_SECRET ?? '').trim() || provisionSecret(root);
	// The /manage sign-in signs its own host-only session. It is verified
	// LOCALLY, so a signed-in manager keeps seeing the site when the CMS is
	// unreachable — the exact moment a maintenance gate is on.
	const sessionSecret =
		String(options.sessionSecret ?? '').trim() ||
		String(process.env.NVOOS_MANAGE_SECRET ?? '').trim() ||
		secret;
	const fetchImpl = options.fetchImpl ?? fetch;
	const log = options.logger ?? ((line) => console.log(line));

	let doc = {
		mode: 'off',
		source: 'build',
		checkedAt: new Date().toISOString(),
		honored: true,
		policy: 'replace',
		page: null,
		comingSoonIndexable: false,
		retryAfterSeconds: 600,
		session: { bypass: true, cookieName: 'nvoos_forge_session' },
		bypass: { cookieName: 'nvoos_gate', ttlSeconds: 43200 },
		managed: { enabled: true, pollSeconds: 60, maxStalenessSeconds: 900 },
	};

	// The build-time verdict IS the boot state: a cold start during a gate must
	// know to gate before its first poll.
	try {
		doc = { ...doc, ...JSON.parse(readFileSync(join(root, 'gate.generated.json'), 'utf8')) };
	} catch {
		// No manifest (a stripped tree): stay off and publish the site.
	}

	const allow = new Set(options.allow ?? DEFAULT_ALLOW);
	const pollSeconds = Math.max(15, positive(doc.managed?.pollSeconds, 60));
	const maxStaleness = Math.max(pollSeconds, positive(doc.managed?.maxStalenessSeconds, 900));
	let lastOk = Date.now();

	/** The effective mode. honored:false means the policy declined it. */
	function mode() {
		return doc.honored === false ? 'off' : validMode(doc.mode);
	}

	function allowed(pathname) {
		for (const entry of allow) {
			// A no-slash entry also covers its directory form: Astro serves both
			// /manage and /manage/, and gating the slashed one locks the manager out
			// of the only sign-in surface (2026-11-26, ECA).
			if (entry.endsWith('/') ? pathname.startsWith(entry) : pathname === entry || pathname === entry + '/') {
				return true;
			}
		}
		return false;
	}

	/** <exp>.<sig> — HMAC over the expiry, so the link is stateless. */
	function bypassToken(now = Date.now()) {
		if (!secret) {
			return '';
		}
		const exp = Math.floor(now / 1000) + positive(doc.bypass?.ttlSeconds, 43200);
		const sig = createHmac('sha256', secret).update('bypass.v1.' + exp).digest('hex');
		return exp + '.' + sig;
	}

	function bypassOk(value) {
		if (!secret || typeof value !== 'string' || !value) {
			return false;
		}
		const cut = value.indexOf('.');
		if (cut === -1) {
			return false;
		}
		const exp = Number(value.slice(0, cut));
		if (!Number.isFinite(exp) || exp * 1000 <= Date.now()) {
			return false;
		}
		const expected = createHmac('sha256', secret).update('bypass.v1.' + exp).digest('hex');
		return safeEqual(value.slice(cut + 1), expected);
	}

	/**
	 * The /manage session: exp.uid.base64url(name).hmac, signed with
	 * 'manage.v1.'. Mirrors src/lib/manage-session.ts — the format is a
	 * CONTRACT between the two files, so a change here is a breaking change
	 * there.
	 */
	function manageSessionOk(req) {
		if (!sessionSecret || doc.session?.bypass === false) {
			return false;
		}
		const value = cookieValue(req, doc.session?.cookieName || 'nvoos_forge_session');
		if (!value) {
			return false;
		}
		const cut = value.lastIndexOf('.');
		if (cut === -1) {
			return false;
		}
		const payload = value.slice(0, cut);
		const parts = payload.split('.');
		if (parts.length !== 3) {
			return false;
		}
		const exp = Number(parts[0]);
		if (!Number.isFinite(exp) || exp * 1000 <= Date.now()) {
			return false;
		}
		const expected = createHmac('sha256', sessionSecret).update('manage.v1.' + payload).digest('hex');
		return safeEqual(value.slice(cut + 1), expected);
	}

	/** Headers for a request the gate lets THROUGH to the real site. */
	function previewHeaders(res, mechanism) {
		res.setHeader('x-nvoos-gate', 'bypass-' + mechanism);
		res.setHeader('x-robots-tag', 'noindex, nofollow');
		res.setHeader('cache-control', 'private, no-store, max-age=0');
		res.setHeader('vary', 'cookie');
	}

	function fallbackHtml(kind) {
		const title = kind === 'maintenance' ? 'Down for maintenance' : 'Coming soon';
		const body =
			kind === 'maintenance'
				? 'We are carrying out planned maintenance. Please try again shortly.'
				: 'This site is not quite ready yet. Please check back soon.';
		return (
			'<!doctype html><html lang="en"><head><meta charset="utf-8" />' +
			'<meta name="viewport" content="width=device-width, initial-scale=1" />' +
			'<meta name="robots" content="noindex, nofollow" />' +
			'<title>' + title + '</title><style>' +
			':root{color-scheme:light dark}' +
			'body{margin:0;min-height:100vh;display:grid;place-items:center;padding:32px;' +
			'font:16px/1.6 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}' +
			'main{max-width:44rem}h1{margin:0 0 .5rem;font-size:2rem}p{margin:0;opacity:.8}' +
			'</style></head><body><main><h1>' + title + '</h1><p>' + body + '</p></main></body></html>'
		);
	}

	/**
	 * Serve the gate page. The prerendered page is the artifact's own
	 * (templates/blog/src/pages/{maintenance,coming-soon}.astro); a stripped
	 * build falls back to the built-in copy so a gate never 500s.
	 */
	function sendGate(req, res, kind) {
		let html = '';
		try {
			html = readFileSync(join(root, 'dist', 'client', kind === 'maintenance' ? 'maintenance' : 'coming-soon', 'index.html'), 'utf8');
		} catch {
			html = fallbackHtml(kind);
		}
		res.statusCode = kind === 'maintenance' ? 503 : 200;
		res.setHeader('content-type', 'text/html; charset=utf-8');
		res.setHeader('cache-control', 'private, no-store, max-age=0');
		res.setHeader('vary', 'cookie');
		if (kind === 'maintenance') {
			res.setHeader('retry-after', String(positive(doc.retryAfter, positive(doc.retryAfterSeconds, 600))));
			res.setHeader('x-robots-tag', 'noindex, nofollow');
		} else if (doc.comingSoonIndexable !== true) {
			res.setHeader('x-robots-tag', 'noindex, nofollow');
		}
		res.setHeader('x-nvoos-gate', kind === 'maintenance' ? 'maintenance' : 'coming-soon');
		res.end(req.method === 'HEAD' ? undefined : html);
	}

	/** POST /api/gate — the signed push (the bridge's fast path). */
	async function push(req, res) {
		if (req.method !== 'POST') {
			res.statusCode = 405;
			res.setHeader('allow', 'POST');
			res.end();
			return;
		}
		if (!pushToken) {
			res.statusCode = 503;
			res.setHeader('content-type', 'application/json; charset=utf-8');
			res.end(JSON.stringify({ ok: false, code: 'push_disabled' }));
			return;
		}
		if (!safeEqual(String(req.headers.authorization ?? ''), 'Bearer ' + pushToken)) {
			res.statusCode = 401;
			res.setHeader('content-type', 'application/json; charset=utf-8');
			res.end(JSON.stringify({ ok: false, code: 'unauthorized' }));
			return;
		}
		let payload = null;
		try {
			payload = JSON.parse(await readBody(req));
		} catch {
			payload = null;
		}
		const next = validMode(payload?.mode);
		doc = {
			...doc,
			mode: next,
			source: 'override',
			checkedAt: new Date().toISOString(),
			page: next === 'maintenance' ? 'maintenance' : next === 'coming_soon' ? 'coming-soon' : null,
		};
		lastOk = Date.now();
		clearTimeout(scheduled);
		schedulePoll();
		res.statusCode = 200;
		res.setHeader('content-type', 'application/json; charset=utf-8');
		res.setHeader('cache-control', 'private, no-store, max-age=0');
		res.end(JSON.stringify({ ok: true, mode: mode() }));
	}

	/**
	 * Poll the bridge. A failure NEVER changes the verdict: the site keeps
	 * publishing (or keeps gating) with the last known state rather than
	 * flapping on a network blip.
	 */
	async function poll() {
		if (!targetSite) {
			return;
		}
		try {
			const response = await fetchImpl(targetSite + '/wp-json/nvoos-forge/v1/gate', {
				headers: { accept: 'application/json' },
				signal: AbortSignal.timeout(10000),
			});
			if (!response.ok) {
				await response.body?.cancel();
				if (Date.now() - lastOk > maxStaleness * 1000) {
					log('[gate] verdict stale (' + response.status + ') — keeping ' + mode());
				}
				return;
			}
			const body = await response.json();
			const next = validMode(body?.maintenance === false ? 'off' : body?.mode);
			lastOk = Date.now();
			if (next !== mode() || body?.plugin !== doc.plugin) {
				doc = {
					...doc,
					mode: next,
					source: 'bridge',
					plugin: typeof body?.plugin === 'string' ? body.plugin : null,
					checkedAt: typeof body?.checkedAt === 'string' ? body.checkedAt : new Date().toISOString(),
					page: next === 'maintenance' ? 'maintenance' : next === 'coming_soon' ? 'coming-soon' : null,
				};
				log('[gate] verdict ' + mode() + ' (bridge)');
			}
		} catch {
			if (Date.now() - lastOk > maxStaleness * 1000) {
				log('[gate] verdict stale (unreachable) — keeping ' + mode());
			}
		}
	}

	let scheduled = null;
	function schedulePoll() {
		if (!targetSite || doc.managed?.enabled === false) {
			return;
		}
		scheduled = setTimeout(async () => {
			await poll();
			schedulePoll();
		}, pollSeconds * 1000);
		if (typeof scheduled.unref === 'function') {
			scheduled.unref();
		}
	}
	schedulePoll();

	return {
		async handle(req, res) {
			const url = new URL(String(req.url ?? '/'), 'http://localhost');
			const pathname = url.pathname;

			if (pathname === '/api/gate') {
				await push(req, res);
				return true;
			}

			// Allowlisted surfaces stay reachable while gated (the staff door,
			// assets, feed and discovery files).
			if (allowed(pathname)) {
				return false;
			}

			// Operator preview link: exchange the token for a host-only cookie and
			// redirect to the same URL without it.
			const token = url.searchParams.get('nvoos-gate');
			if (token !== null) {
				if (!bypassOk(token)) {
					res.statusCode = 403;
					res.setHeader('cache-control', 'private, no-store, max-age=0');
					res.setHeader('x-robots-tag', 'noindex, nofollow');
					res.end('This preview link is not valid.');
					return true;
				}
				url.searchParams.delete('nvoos-gate');
				res.statusCode = 302;
				res.setHeader('location', url.pathname + (url.search || ''));
				res.setHeader('cache-control', 'private, no-store, max-age=0');
				res.setHeader(
					'set-cookie',
					(doc.bypass?.cookieName || 'nvoos_gate') +
						'=' +
						encodeURIComponent(token) +
						'; Path=/; HttpOnly; SameSite=Lax; Max-Age=' +
						positive(doc.bypass?.ttlSeconds, 43200) +
						(String(req.headers['x-forwarded-proto'] ?? '') === 'https' ? '; Secure' : '')
				);
				res.end();
				return true;
			}

			const current = mode();
			if (current === 'off') {
				return false;
			}

			// A verified manager session sees the real site (the Elementor
			// behaviour), verified with no CMS round-trip.
			if (manageSessionOk(req)) {
				previewHeaders(res, 'manage');
				return false;
			}
			if (bypassOk(cookieValue(req, doc.bypass?.cookieName || 'nvoos_gate'))) {
				previewHeaders(res, 'link');
				return false;
			}

			sendGate(req, res, current === 'maintenance' ? 'maintenance' : 'coming-soon');
			return true;
		},
		close() {
			if (scheduled) {
				clearTimeout(scheduled);
				scheduled = null;
			}
		},
		state() {
			return { mode: mode(), source: doc.source, checkedAt: doc.checkedAt, plugin: doc.plugin ?? null };
		},
		bypassUrl(pathname = '/') {
			const token = bypassToken();
			return token ? pathname + (pathname.includes('?') ? '&' : '?') + 'nvoos-gate=' + token : '';
		},
	};
}
`;

/**
 * The emitted `forge-gate/static.mjs` — a bounded static file server.
 *
 * The front controller must serve `dist/client` ITSELF (the gate runs before
 * Astro), so this is deliberately small: no directory listings, no dotfiles,
 * no traversal, and it returns false for anything it does not own so the Astro
 * handler can render the route instead.
 */
const SOURCE_STATIC = String.raw`// Generated by NV oOS Astro Forge — static handler for the front controller.
//
// Serves dist/client only. A path that escapes the root is treated as "not
// mine" (the request falls through to Astro, which 404s it) — the server never
// stats a file outside the build tree.

import { createReadStream } from 'node:fs';
import { stat } from 'node:fs/promises';
import { extname, resolve, sep } from 'node:path';

const TYPES = {
	'.html': 'text/html; charset=utf-8',
	'.css': 'text/css; charset=utf-8',
	'.js': 'text/javascript; charset=utf-8',
	'.mjs': 'text/javascript; charset=utf-8',
	'.json': 'application/json; charset=utf-8',
	'.xml': 'application/xml; charset=utf-8',
	'.txt': 'text/plain; charset=utf-8',
	'.svg': 'image/svg+xml',
	'.png': 'image/png',
	'.jpg': 'image/jpeg',
	'.jpeg': 'image/jpeg',
	'.webp': 'image/webp',
	'.avif': 'image/avif',
	'.gif': 'image/gif',
	'.ico': 'image/x-icon',
	'.woff': 'font/woff',
	'.woff2': 'font/woff2',
	'.ttf': 'font/ttf',
	'.pdf': 'application/pdf',
	'.md': 'text/markdown; charset=utf-8',
};

/** How long a response may be cached, by path family. */
function cacheControl(pathname) {
	if (pathname.startsWith('/_astro/')) {
		// Content-hashed by the bundler.
		return 'public, max-age=31536000, immutable';
	}
	if (pathname.startsWith('/manage-assets/')) {
		// A fixed URL whose bytes change when the bundle is rebuilt; SRI makes a
		// stale copy fail loudly, and revalidation makes it rare.
		return 'no-cache';
	}
	if (pathname.endsWith('.html') || pathname.endsWith('/')) {
		return 'no-cache';
	}
	return 'public, max-age=300, must-revalidate';
}

export function createStatic(rootDir) {
	const root = resolve(rootDir);

	async function handle(req, res) {
		if (req.method !== 'GET' && req.method !== 'HEAD') {
			return false;
		}
		let requestUrl;
		let pathname;
		try {
			requestUrl = new URL(String(req.url ?? '/'), 'http://localhost');
			pathname = decodeURIComponent(requestUrl.pathname);
		} catch {
			return false;
		}
		if (pathname.includes('\u0000')) {
			return false;
		}
		if (pathname.endsWith('/')) {
			pathname += 'index.html';
		}
		const file = resolve(root, '.' + pathname);
		if (file !== root && !file.startsWith(root + sep)) {
			// Traversal attempt: not ours. Astro answers 404.
			return false;
		}
		const info = await stat(file).catch(() => null);
		if (!info || !info.isFile()) {
			// Directory-index canonicalisation. build.format 'directory' writes a
			// page to <slug>/index.html only, so /about-us matches no route on a
			// managed build and would 404. WordPress 301s that form instead, and
			// every legacy inbound link and the sitemap canonical depend on it.
			if (!pathname.endsWith('/index.html')) {
				const index = resolve(root, '.' + pathname + '/index.html');
				if (index !== root && index.startsWith(root + sep)) {
					const indexInfo = await stat(index).catch(() => null);
					if (indexInfo && indexInfo.isFile()) {
						res.statusCode = 301;
						res.setHeader('location', pathname + '/' + requestUrl.search);
						res.setHeader('content-type', 'text/plain; charset=utf-8');
						if (!res.hasHeader('cache-control')) {
							res.setHeader('cache-control', 'public, max-age=300, must-revalidate');
						}
						res.end();
						return true;
					}
				}
			}
			return false;
		}
		res.statusCode = 200;
		res.setHeader('content-type', TYPES[extname(file).toLowerCase()] ?? 'application/octet-stream');
		res.setHeader('content-length', String(info.size));
		// NEVER clobber a header the gate already set: a bypassed request carries
		// cache-control: no-store from previewHeaders(), and the static layer must
		// not upgrade it to a cacheable value.
		if (!res.hasHeader('cache-control')) {
			res.setHeader('cache-control', cacheControl(pathname));
		}
		if (req.method === 'HEAD') {
			res.end();
			return true;
		}
		await new Promise((done) => {
			const stream = createReadStream(file);
			stream.on('error', () => {
				if (!res.headersSent) {
					res.statusCode = 500;
				}
				res.end();
				done();
			});
			stream.on('end', done);
			stream.pipe(res);
		});
		return true;
	}

	return { handle };
}
`;

/**
 * The emitted `server.js` — the front controller Velocity runs as its entry.
 *
 * Astro's node adapter in `mode: 'middleware'` exports a `handler` and binds no
 * listener of its own, which is what lets the gate answer BEFORE the static
 * handler and the router.
 */
const SOURCE_SERVER = String.raw`// Generated by NV oOS Astro Forge — managed front controller (Proposal 165).
//
// Order matters and is the whole point of this file:
//   1. the publication gate (503/coming-soon, bypass, manager session)
//   2. dist/client (prerendered HTML and assets)
//   3. the Astro handler (everything else: /api/*, SSR routes)
//
// A failure anywhere is a 500 with a typed message, never a hung socket.

import { createServer } from 'node:http';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { handler } from './dist/server/entry.mjs';
import { createGate } from './forge-gate/runtime.mjs';
import { createStatic } from './forge-gate/static.mjs';

const root = dirname(fileURLToPath(import.meta.url));
const gate = createGate({ root });
const statics = createStatic(join(root, 'dist', 'client'));

const rawPublicHost = (() => {
	try {
		return new URL(process.env.ASTRO_SITE || '').hostname.toLowerCase();
	} catch {
		return '';
	}
})();
const publicHost = rawPublicHost.replace(/^www\./, '');
const knownHosts = publicHost ? [publicHost, 'www.' + publicHost] : [];

const server = createServer((req, res) => {
	(async () => {
		// The proxy rewrites Host, so Astro cannot match the Origin alone.
		// This is the configured origin, not a client value; Astro accepts it
		// only because astro.config.mjs lists it in security.allowedDomains.
		if (publicHost) {
			// Keep the host the CLIENT used when it is one of this app's own names.
			// Astro compares Origin with Astro.url, so pinning EVERY request to the
			// apex makes a www visitor unrepresentable: the Origin can never match
			// and every POST is refused (2026-11-26).
			const incoming = String(req.headers['x-forwarded-host'] || req.headers.host || '')
				.split(',')[0]
				.trim()
				.toLowerCase();
			req.headers['x-forwarded-host'] =
				knownHosts.indexOf(incoming) === -1 ? publicHost : incoming;
			req.headers['x-forwarded-proto'] = 'https';
		}
		if (await gate.handle(req, res)) {
			return;
		}
		if (await statics.handle(req, res)) {
			return;
		}
		handler(req, res);
	})().catch((error) => {
		console.error('[server] ' + (error && error.stack ? error.stack : String(error)));
		if (!res.headersSent) {
			res.statusCode = 500;
			res.setHeader('content-type', 'text/plain; charset=utf-8');
			res.setHeader('cache-control', 'private, no-store, max-age=0');
		}
		res.end('Internal error');
	});
});

const port = Number(process.env.PORT) || 4321;
const host = String(process.env.HOST || '0.0.0.0');
server.listen(port, host, () => {
	const state = gate.state();
	console.log('[server] listening on ' + host + ':' + port + ' (gate ' + state.mode + ', ' + state.source + ')');
});

for (const signal of ['SIGTERM', 'SIGINT']) {
	process.on(signal, () => {
		gate.close();
		server.close(() => process.exit(0));
	});
}
`;


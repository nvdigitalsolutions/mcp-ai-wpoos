/**
 * A reference static handler for callers that need one in-process (tests, the
 * static publish path). Behaviourally identical to the emitted module above —
 * keep the two in step.
 */
export function createStatic( rootDir: string ): {
	handle( req: { method?: string; url?: string }, res: unknown ): Promise< boolean >;
} {
	const root = path.resolve( rootDir );
	return {
		async handle( req, res ) {
			const response = res as {
				statusCode: number;
				setHeader( name: string, value: string ): void;
				hasHeader( name: string ): boolean;
				end( body?: string ): void;
			};
			if ( req.method !== 'GET' && req.method !== 'HEAD' ) {
				return false;
			}
			let requestUrl: URL;
			let pathname: string;
			try {
				requestUrl = new URL( String( req.url ?? '/' ), 'http://localhost' );
				pathname = decodeURIComponent( requestUrl.pathname );
			} catch {
				return false;
			}
			if ( pathname.endsWith( '/' ) ) {
				pathname += 'index.html';
			}
			const file = path.resolve( root, `.${ pathname }` );
			if ( file !== root && ! file.startsWith( root + path.sep ) ) {
				return false;
			}
			const info = await stat( file ).catch( () => null );
			if ( ! info || ! info.isFile() ) {
				// Directory-index canonicalisation — see the emitted module above.
				if ( ! pathname.endsWith( '/index.html' ) ) {
					const index = path.resolve( root, `.${ pathname }/index.html` );
					if ( index !== root && index.startsWith( root + path.sep ) ) {
						const indexInfo = await stat( index ).catch( () => null );
						if ( indexInfo && indexInfo.isFile() ) {
							response.statusCode = 301;
							response.setHeader( 'location', pathname + '/' + requestUrl.search );
							response.setHeader( 'content-type', 'text/plain; charset=utf-8' );
							if ( ! response.hasHeader( 'cache-control' ) ) {
								response.setHeader( 'cache-control', 'public, max-age=300, must-revalidate' );
							}
							response.end();
							return true;
						}
					}
				}
				return false;
			}
			response.statusCode = 200;
			response.setHeader( 'content-type', 'application/octet-stream' );
			response.setHeader( 'content-length', String( info.size ) );
			if ( req.method === 'HEAD' ) {
				response.end();
				return true;
			}
			await new Promise< void >( ( done ) => {
				const stream = createReadStream( file );
				stream.on( 'error', () => {
					response.end();
					done();
				} );
				stream.on( 'end', done );
				stream.on( 'data', ( chunk ) => response.setHeader( 'x-nvoos-bytes', String( chunk.length ) ) );
				stream.resume();
			} );
			response.end();
			return true;
		},
	};
}

/** The token-gated revalidate endpoint (ships regardless of the proxy). */
export function renderRevalidateTs(): string {
	return [
		'// Generated by NV oOS Astro Forge — cache revalidation (Proposal 135).',
		'//',
		'// POST /api/revalidate  Authorization: Bearer <NVOOS_REVALIDATE_TOKEN>',
		'// Body: { "tags": ["products", "products:42"] } or { "path": "/products/42/" }',
		'//',
		'// Fail-closed: no token configured disables the route entirely.',
		"import type { APIRoute } from 'astro';",
		'',
		"const TOKEN = process.env.NVOOS_REVALIDATE_TOKEN ?? '';",
		'',
		'export const prerender = false;',
		'',
		'export const POST: APIRoute = async ({ request, cache }) => {',
		'\tif (!TOKEN) {',
		"\t\treturn new Response('Revalidation is not configured.', { status: 503 });",
		'\t}',
		'\tif (request.headers.get("authorization") !== `Bearer ${TOKEN}`) {',
		"\t\treturn new Response('Unauthorized', { status: 401 });",
		'\t}',
		'',
		'\tconst body = (await request.json().catch(() => null)) as',
		'\t\t| { tags?: unknown; path?: unknown }',
		'\t\t| null;',
		'\tconst tags = Array.isArray(body?.tags) ? body.tags.map(String) : [];',
		'\tconst path = typeof body?.path === "string" ? body.path : "";',
		'\tif (!tags.length && !path) {',
		"\t\treturn new Response('Provide { tags: string[] } or { path: string }.', { status: 400 });",
		'\t}',
		'',
		'\tif (tags.length) {',
		'\t\tawait cache.invalidate({ tags });',
		'\t}',
		'\tif (path) {',
		'\t\tawait cache.invalidate({ path });',
		'\t}',
		'',
		"\treturn new Response('ok');",
		'};',
		'',
	].join('\n');
}

/**
 * `/api/preview` — the token exchange (Proposal 135 Phase 5).
 *
 * `/manage` mints a short-lived token on the CMS and hands the editor this
 * URL. The route stores the token in a HOST-ONLY cookie and redirects to the
 * draft-aware SSR page. It never verifies the token — the same tokens are
 * verified by the bridge, so the frontend holds no key material and cannot
 * mint one.
 */
export function renderPreviewApiTs(): string {
	return [
		'// Generated by NV oOS Astro Forge — preview exchange (Proposal 135).',
		'//',
		'// GET /api/preview?token=<bridge token>&slug=<slug>',
		'//   → Set-Cookie: nvoos_preview=<token>; HttpOnly; SameSite=Lax; Path=/',
		'//   → 302 /preview/<slug>/',
		'//',
		'// No Domain attribute on purpose: the cookie is host-only, so it works on',
		'// this site and is never sent to the CMS host.',
		"import type { APIRoute } from 'astro';",
		'',
		"const COOKIE = 'nvoos_preview';",
		"const MAX_AGE = 900;",
		'',
		'/** Only a plain slug is accepted — never a path or an absolute URL. */',
		'function safeSlug(value: string | null): string | null {',
		'\tconst slug = (value ?? \'\').trim();',
		"\treturn /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) ? slug : null;",
		'}',
		'',
		'export const prerender = false;',
		'',
		'export const GET: APIRoute = async ({ url, cookies, redirect }) => {',
		"\tconst token = url.searchParams.get('token') ?? '';",
		"\tconst slug = safeSlug(url.searchParams.get('slug'));",
		'\tif (!token || !slug) {',
		"\t\treturn new Response('Preview link is incomplete.', { status: 400 });",
		'\t}',
		'',
		'\tcookies.set(COOKIE, token, {',
		"\t\tpath: '/',",
		'\t\thttpOnly: true,',
		"\t\tsameSite: 'lax',",
		"\t\tsecure: url.protocol === 'https:',",
		'\t\tmaxAge: MAX_AGE,',
		'\t});',
		'',
		'\tconst response = redirect(`/preview/${slug}/`, 302);',
		"\tresponse.headers.set('cache-control', 'no-store');",
		'\treturn response;',
		'};',
		'',
	].join('\n');
}

/**
 * `/preview/<slug>/` — the draft-aware render (Proposal 135 Phase 5).
 *
 * SSR only (managed tier). Reads the host-only cookie, asks the bridge for
 * exactly the one document the token unlocks, and renders it. Never indexed,
 * never cached: a preview is one editor looking at one draft.
 */
export function renderPreviewPageTs(): string {
	return [
		'---',
		'// Generated by NV oOS Astro Forge — draft preview page (Proposal 135).',
		'//',
		'// /preview/<slug>/ renders ONE document the preview token unlocks. It is',
		'// deliberately separate from the real content routes: a draft has no',
		'// published URL, and preview traffic must never touch the public cache.',
		"import Base from '../../layouts/Base.astro';",
		"import { WpClient, WpClientError } from '../../forge/wp-client.ts';",
		"import { sanitizeHtml } from '../../forge/sanitize.ts';",
		"import { extractPayloadRaw } from '../../forge/wp-loader.ts';",
		"import manifest from '../../../nvoos.json';",
		'',
		'export const prerender = false;',
		'',
		"const COOKIE = 'nvoos_preview';",
		"const NO_STORE = 'private, no-store';",
		"const NO_INDEX = 'noindex, nofollow';",
		'',
		"const slug = String(Astro.params.slug ?? '').replace(/^\\/+|\\/+$/g, '');",
		"const token = Astro.cookies.get(COOKIE)?.value ?? '';",
		'',
		'// Preview responses must never be cached or indexed, on every path.',
		"Astro.response.headers.set('cache-control', NO_STORE);",
		"Astro.response.headers.set('x-robots-tag', NO_INDEX);",
		'',
		'if (!token || !slug) {',
		"\treturn new Response('Preview link is missing or expired.', { status: 404 });",
		'}',
		'',
		"const localCollection = manifest.collections.find((entry) => entry.source === 'local');",
		'if (!localCollection) {',
		"\treturn new Response('This site has no local content collection.', { status: 404 });",
		'}',
		'',
		"const siteUrl = (import.meta.env.WP_SITE_URL ?? manifest.url ?? '').replace(/\\/+$/, '');",
		'const client = new WpClient({ baseUrl: siteUrl });',
		'',
		'let doc: Record<string, unknown> | undefined;',
		'try {',
		'\tconst { body } = await client.get<{ docs?: Array<Record<string, unknown>> }>(',
		'\t\tlocalCollection.restBase || \'nvoos-commerce/v1/local\',',
		'\t\t{ preview_token: token, \'where[slug][equals]\': slug }',
		'\t);',
		'\tdoc = (body.docs ?? [])[0];',
		'} catch (error) {',
		'\tif (error instanceof WpClientError) {',
		"\t\treturn new Response('Preview is unavailable.', { status: 502 });",
		'\t}',
		'\tthrow error;',
		'}',
		'',
		'if (!doc) {',
		'\t// An expired token, a deleted document and a wrong slug are one answer:',
		'\t// the preview does not exist.',
		"\treturn new Response('Preview not found. The link may have expired.', { status: 404 });",
		'}',
		'',
		'const raw = extractPayloadRaw(doc);',
		'---',
		'',
		'<Base title={raw.title} description={raw.excerpt} seo={{ robots: NO_INDEX }}>',
		'\t<article class="post preview">',
		'\t\t<header>',
		'\t\t\t<h1>{raw.title}</h1>',
		'\t\t\t<p class="preview-badge">Draft preview — not published</p>',
		'\t\t</header>',
		'\t\t<div class="post-body" set:html={sanitizeHtml(raw.html)} />',
		'\t</article>',
		'</Base>',
		'',
	].join('\n');
}


// ---------------------------------------------------------------------------
// managed-runtime.ts — the managed deploy tier's emitted runtime files
// (Proposal 135 Phase 2).
//
// A `managed` forged site ships a Node entry beside the built `dist/`:
//
//   src/lib/managed-proxy.ts        the shared server-to-server proxy helper
//   src/pages/api/[...path].ts      /api/*  → the commerce contract
//   src/pages/api/forms/submit.ts   → the forge-bridge forms route
//   src/pages/api/revalidate.ts     token-gated, tag-based cache invalidation
//   src/pages/media/[...path].ts    /media/* → the WordPress uploads dir
//   server.js                       the Velocity entry (PM2 needs the root
//                                   entry); boots the Astro node adapter
//   scripts/sync-deploy-tree.mjs    assembles .deploy/ = dist/ + server.js +
//                                   runtime package.json for the mirror push
//
// WHY ROUTES, NOT `src/fetch.ts` (learned 2026-11-09): a custom fetch handler
// replaces Astro's request pipeline, and Astro then warns that the project's
// sessions, actions, middleware and cache handlers are NOT wired — a managed
// site would silently lose customer sessions and route caching. Endpoint
// routes run inside the normal pipeline, so everything keeps working; the
// only thing they add is the server-to-server hop.
//
// Everything here is emitted as TEXT — no WordPress credentials, no tokens.
// The operator supplies NVOOS_TARGET_SITE / NVOOS_REVALIDATE_TOKEN as
// environment variables in the Velocity app.
// ---------------------------------------------------------------------------

/** The shared proxy helper (server-to-server; cookies re-scoped host-only). */
export function renderProxyHelperTs(): string {
	return [
		'// Generated by NV oOS Astro Forge — managed proxy (Proposal 135).',
		'//',
		'// Reaches WordPress SERVER-TO-SERVER. The CMS host never needs to be',
		'// publicly reachable from a browser, so there is no CORS surface: the',
		'// browser only ever talks to this origin.',
		'',
		"const TARGET = (process.env.NVOOS_TARGET_SITE ?? '').replace(/\\/+$/, '');",
		"const PUBLIC_ORIGIN = (process.env.ASTRO_SITE ?? '').replace(/\\/+$/, '');",
		'',
		'/** The CMS sets cookies for its own host; the browser must see them as',
		' *  host-only on the public origin (domain cookies are stripped). */',
		'function hostOnlyCookie(value: string): string {',
		'\treturn value.replace(/;\\s*Domain=[^;]+/gi, "");',
		'}',
		'',
		'/** Rest-param guard: no absolute paths and no traversal. */',
		'export function sanitizeRestPath(value: string | undefined): string | null {',
		"\tconst path = (value ?? '').replace(/^\\/+/, '');",
		"\tif (!path || path.includes('..')) {",
		'\t\treturn null;',
		'\t}',
		'\treturn path;',
		'}',
		'',
		'export async function proxyToWordPress(request: Request, targetPath: string): Promise<Response> {',
		'\tif (!TARGET) {',
		"\t\treturn new Response('NVOOS_TARGET_SITE is not configured.', { status: 503 });",
		'\t}',
		'',
		'\tconst url = new URL(request.url);',
		'\tconst headers = new Headers(request.headers);',
		"\theaders.delete('host');",
		"\theaders.delete('origin');",
		'\t// A same-origin browser request becomes a server-to-server call.',
		'\tif (PUBLIC_ORIGIN) {',
		"\t\theaders.set('origin', PUBLIC_ORIGIN);",
		'\t}',
		'',
		'\tconst init: RequestInit = { method: request.method, headers, redirect: "manual" };',
		"\tif (request.method !== 'GET' && request.method !== 'HEAD') {",
		'\t\tinit.body = await request.arrayBuffer();',
		'\t}',
		'',
		'\tconst upstream = await fetch(`${TARGET}${targetPath}${url.search}`, init);',
		'\tconst responseHeaders = new Headers(upstream.headers);',
		'\tconst getSetCookie = (upstream.headers as Headers & { getSetCookie?: () => string[] }).getSetCookie;',
		'\tconst cookies = typeof getSetCookie === "function" ? getSetCookie.call(upstream.headers) : [];',
		'\tif (cookies.length) {',
		"\t\tresponseHeaders.delete('set-cookie');",
		'\t\tfor (const cookie of cookies) {',
		"\t\t\tresponseHeaders.append('set-cookie', hostOnlyCookie(cookie));",
		'\t\t}',
		'\t}',
		'',
		'\treturn new Response(upstream.body, {',
		'\t\tstatus: upstream.status,',
		'\t\tstatusText: upstream.statusText,',
		'\t\theaders: responseHeaders,',
		'\t});',
		'}',
		'',
	].join('\n');
}


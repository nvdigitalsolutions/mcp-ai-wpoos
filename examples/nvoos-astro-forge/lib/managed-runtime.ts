/**
 * The deploy-tree assembler the mirror push consumes as SOURCE_DIR=.deploy.
 *
 * The runtime manifest it writes MUST declare the project's dependencies. The
 * Astro node adapter externalizes its runtime (`cookie`, `devalue`,
 * `html-escaper`, `piccolore`, `send`, `server-destroy`, `unstorage`,
 * `@oslojs/encoding`, …), so a dependency-free manifest makes Velocity's
 * `npm install` a no-op, `node server.js` throws ERR_MODULE_NOT_FOUND, the
 * release never promotes, and the app silently keeps serving an older build.
 */
export function renderSyncDeployTree(): string {
	return [
		'#!/usr/bin/env node',
		'// sync-deploy-tree.mjs — assemble the managed deploy tree (Proposal 135).',
		'//',
		'// .deploy/ = dist/ + server.js + a runtime package.json, which is what the',
		'// shared mirror branch carries. mirror-push.mjs consumes it via',
		'// SOURCE_DIR=.deploy; the branch root then runs `node server.js`.',
		'//',
		'// The manifest carries the project dependencies (and its lockfile): the',
		'// Astro node adapter externalizes its runtime, so Velocity has to install',
		'// them. Declaring none installs nothing, `node server.js` dies on',
		'// ERR_MODULE_NOT_FOUND, and the release is never promoted.',
		"import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';",
		"import { join, resolve } from 'node:path';",
		'',
		'const root = resolve(process.cwd());',
		"const out = join(root, '.deploy');",
		"const dist = join(root, 'dist');",
		"const entry = join(root, 'server.js');",
		'',
		'if (!existsSync(dist)) {',
		"\tconsole.error('sync-deploy-tree: dist/ is missing — run `npm run build` first.');",
		'\tprocess.exit(1);',
		'}',
		'if (!existsSync(entry)) {',
		"\tconsole.error('sync-deploy-tree: server.js is missing — is this a managed project?');",
		'\tprocess.exit(1);',
		'}',
		'',
		"const projectPkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));",
		'const dependencies = projectPkg.dependencies ?? {};',
		'',
		'if (Object.keys(dependencies).length === 0) {',
		"\tconsole.error('sync-deploy-tree: package.json declares no dependencies.');",
		"\tconsole.error('  The managed runtime boots the Astro node adapter, which imports its');",
		"\tconsole.error('  runtime packages from node_modules — Velocity installs from this manifest.');",
		"\tconsole.error('  Move the SSR build dependencies (astro, @astrojs/node, …) into dependencies.');",
		'\tprocess.exit(1);',
		'}',
		'',
		'rmSync(out, { recursive: true, force: true });',
		'mkdirSync(out, { recursive: true });',
		"cpSync(dist, join(out, 'dist'), { recursive: true });",
		"cpSync(entry, join(out, 'server.js'));",
		'',
		'// The emitted manifest mirrors the project dependency set, so the project',
		'// lockfile is valid here; .npmrc carries any install flags.',
		"for (const name of ['package-lock.json', 'npm-shrinkwrap.json', '.npmrc']) {",
		'\tif (existsSync(join(root, name))) {',
		'\t\tcpSync(join(root, name), join(out, name));',
		'\t}',
		'}',
		'',
		'writeFileSync(',
		"\tjoin(out, 'package.json'),",
		'\tJSON.stringify(',
		'\t\t{',
		"\t\t\tname: 'nvoos-forge-site',",
		"\t\t\tversion: '1.0.0',",
		'\t\t\tprivate: true,',
		"\t\t\ttype: 'module',",
		"\t\t\tscripts: { build: 'node -e \"process.exit(0)\"', start: 'node server.js' },",
		"\t\t\tengines: { node: '>=22.23.4' },",
		'\t\t\tdependencies,',
		'\t\t},',
		'\t\tnull,',
		'\t\t2',
		'\t) + \'\\n\'',
		');',
		'',
		'// Fail closed on an under-declared manifest: every bare import in the build',
		'// output must be reachable from the declared dependency closure. The build',
		'// machine resolved them, so an unreachable one means the published tree',
		'// cannot boot — catch it here instead of in a failed Velocity release.',
		'const SPECIFIER = /(?:from\\s*|import\\s*\\(\\s*|require\\s*\\(\\s*|import\\s*)[\"\']([^\"\'\\n]+)[\"\']/g;',
		'',
		'function* walk(dir) {',
		'\tfor (const name of readdirSync(dir)) {',
		'\t\tconst full = join(dir, name);',
		'\t\tif (statSync(full).isDirectory()) {',
		'\t\t\tyield* walk(full);',
		'\t\t} else if (/.\\.(?:mjs|cjs|js)$/.test(name)) {',
		'\t\t\tyield full;',
		'\t\t}',
		'\t}',
		'}',
		'',
		'function packageName(specifier) {',
		"\tif (specifier.startsWith('.') || specifier.startsWith('/')) {",
		'\t\treturn null;',
		'\t}',
		'\t// node: builtins and the astro: virtual modules are not installable.',
		'\tif (/^[a-z][a-z0-9+.-]*:/i.test(specifier)) {',
		'\t\treturn null;',
		'\t}',
		"\tconst parts = specifier.split('/');",
		"\treturn specifier.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];",
		'}',
		'',
		"const imported = new Set();",
		"for (const file of walk(join(out, 'dist'))) {",
		"\tfor (const match of readFileSync(file, 'utf8').matchAll(SPECIFIER)) {",
		'\t\tconst name = packageName(match[1]);',
		'\t\tif (name) {',
		'\t\t\timported.add(name);',
		'\t\t}',
		'\t}',
		'}',
		'',
		'// Walk the declared closure through the installed tree (npm hoists, so a',
		'// transitive of astro is a direct child of node_modules).',
		'const reachable = new Set();',
		'const queue = Object.keys(dependencies);',
		'while (queue.length > 0) {',
		'\tconst name = queue.pop();',
		'\tif (reachable.has(name)) {',
		'\t\tcontinue;',
		'\t}',
		'\treachable.add(name);',
		"\tconst manifest = join(root, 'node_modules', name, 'package.json');",
		'\tif (!existsSync(manifest)) {',
		'\t\tcontinue;',
		'\t}',
		'\tlet meta;',
		'\ttry {',
		"\t\tmeta = JSON.parse(readFileSync(manifest, 'utf8'));",
		'\t} catch {',
		'\t\tcontinue;',
		'\t}',
		"\tfor (const field of ['dependencies', 'optionalDependencies', 'peerDependencies']) {",
		'\t\tfor (const dep of Object.keys(meta[field] ?? {})) {',
		'\t\t\tqueue.push(dep);',
		'\t\t}',
		'\t}',
		'}',
		'',
		'// Only real, installed packages can be missing — anything else in the scan',
		'// is a string literal that happens to look like an import.',
		"const missing = [...imported].filter((name) => !reachable.has(name) && existsSync(join(root, 'node_modules', name)));",
		'if (missing.length > 0) {',
		"\tconsole.error('sync-deploy-tree: the build imports packages the manifest does not declare:');",
		'\tfor (const name of missing.sort()) {',
		"\t\tconsole.error('  - ' + name);",
		'\t}',
		"\tconsole.error('  Add them to the project dependencies so Velocity installs them.');",
		'\tprocess.exit(1);',
		'}',
		'',
		'console.log(',
		"\t'sync-deploy-tree: .deploy/ ready (' + out + ') — ' + Object.keys(dependencies).length + ' runtime dependencies declared'",
		');',
		'',
	].join('\n');
}

/**
 * The pre-publish boot gate (SOURCE_DIR=.deploy → npm install → node server.js).
 *
 * The forge can assemble a tree that builds but cannot start: anything the
 * runtime manifest forgets only surfaces when `node server.js` resolves its
 * imports. Velocity then fails the release and quietly keeps serving the
 * previous build, so CI stays green while the site freezes (2026-11-10).
 */
export function renderVerifyDeployTree(): string {
	return [
		'#!/usr/bin/env node',
		'// verify-deploy-tree.mjs — boot the emitted .deploy tree the way Velocity will.',
		'//',
		'// Installs from the emitted manifest in a temp copy and starts the entry,',
		'// so a tree that cannot boot never reaches the mirror branch. Pass criterion:',
		'// the process is still alive AND answers HTTP on /. Any status counts — the',
		'// runner may not reach the CMS, and a 500 from an unreachable origin still',
		'// proves the router booted. The failure this exists for (a module-resolution',
		'// crash at import time) never answers at all.',
		"import { execFileSync, spawn } from 'node:child_process';",
		"import { cpSync, existsSync, mkdtempSync, rmSync } from 'node:fs';",
		"import { get } from 'node:http';",
		"import { tmpdir } from 'node:os';",
		"import { join, resolve } from 'node:path';",
		'',
		'const root = resolve(process.cwd());',
		"const tree = join(root, '.deploy');",
		'const timeoutMs = Number(process.env.DEPLOY_TREE_TIMEOUT_MS ?? 60000);',
		'const port = Number(process.env.DEPLOY_TREE_PORT ?? 33917);',
		'',
		"if (!existsSync(join(tree, 'server.js'))) {",
		"\tconsole.error('verify-deploy-tree: .deploy/server.js is missing — run scripts/sync-deploy-tree.mjs first.');",
		'\tprocess.exit(1);',
		'}',
		'',
		'function npm(args, cwd) {',
		'\t// Windows resolves npm through the cmd shim; going through ComSpec keeps',
		'\t// the arguments off a raw shell string (no DEP0190 concatenation warning).',
		"\tif (process.platform === 'win32') {",
		"\t\texecFileSync(process.env.ComSpec ?? 'cmd.exe', ['/d', '/s', '/c', 'npm', ...args], { cwd, stdio: 'inherit' });",
		'\t\treturn;',
		'\t}',
		"\texecFileSync('npm', args, { cwd, stdio: 'inherit' });",
		'}',
		'',
		'function probe(url, budget) {',
		'\treturn new Promise((settle) => {',
		'\t\tconst started = Date.now();',
		'\t\tconst attempt = () => {',
		'\t\t\tconst req = get(url, (res) => {',
		'\t\t\t\tres.resume();',
		'\t\t\t\tsettle({ status: res.statusCode });',
		'\t\t\t});',
		'\t\t\treq.on(\'error\', () => {',
		'\t\t\t\tif (Date.now() - started > budget) {',
		'\t\t\t\t\tsettle({ status: 0 });',
		'\t\t\t\t} else {',
		'\t\t\t\t\tsetTimeout(attempt, 250);',
		'\t\t\t\t}',
		'\t\t\t});',
		'\t\t\treq.setTimeout(2000, () => req.destroy());',
		'\t\t};',
		'\t\tattempt();',
		'\t});',
		'}',
		'',
		"const tmp = mkdtempSync(join(tmpdir(), 'forge-boot-'));",
		'\tlet child;',
		'\tlet exited;',
		"\tlet stderr = '';",
		'\tlet failure = null;',
		'\ttry {',
		'\t\tcpSync(tree, tmp, { recursive: true });',
		"\t\tnpm(['install', '--omit=dev', '--no-audit', '--no-fund'], tmp);",
		"\t\tchild = spawn(process.execPath, ['server.js'], {",
		'\t\t\tcwd: tmp,',
		"\t\t\tstdio: ['ignore', 'pipe', 'pipe'],",
		"\t\t\tenv: { ...process.env, PORT: String(port), HOST: '127.0.0.1', NODE_ENV: 'production' },",
		'\t\t});',
		'\t\tchild.stderr.on(\'data\', (chunk) => {',
		'\t\t\tstderr += chunk;',
		'\t\t});',
		"\t\texited = new Promise((settle) => child.once('exit', (code) => settle(code ?? 1)));",
		'\t\tconst result = await Promise.race([probe(`http://127.0.0.1:${port}/`, timeoutMs), exited.then(() => null)]);',
		'\t\tif (result === null) {',
		"\t\t\tthrow new Error('verify-deploy-tree: the entry exited before answering (code ' + (await exited) + ').');",
		'\t\t}',
		'\t\tif (result.status === 0) {',
		"\t\t\tthrow new Error('verify-deploy-tree: no HTTP response on port ' + port + ' within ' + timeoutMs + 'ms.');",
		'\t\t}',
		'\t\tif (stderr.trim()) {',
		"\t\t\tconsole.log('verify-deploy-tree: stderr — ' + stderr.trim().split('\\n')[0]);",
		'\t\t}',
		"\t\tconsole.log('verify-deploy-tree: booted (HTTP ' + result.status + ') — the deploy tree can start on Velocity.');",
		'\t} catch (error) {',
		'\t\tfailure = error;',
		'\t} finally {',
		'\t\tif (child && child.exitCode === null) {',
		"\t\t\tchild.kill('SIGTERM');",
		'\t\t\tawait Promise.race([exited ?? Promise.resolve(0), new Promise((settle) => setTimeout(settle, 5000))]);',
		'\t\t}',
		'\t\t// Windows keeps node_modules handles open briefly after the process',
		'\t\t// exits; a leaked temp dir must never fail a passing gate.',
		'\t\ttry {',
		'\t\t\trmSync(tmp, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });',
		'\t\t} catch {',
		'\t\t\t// best effort — the OS reclaims it',
		'\t\t}',
		'\t}',
		'',
		'\tif (failure) {',
		'\t\tconsole.error(failure.message);',
		'\t\tif (stderr.trim()) {',
		'\t\t\tconsole.error(stderr.trim());',
		'\t\t}',
		'\t\tprocess.exit(1);',
		'\t}',
		'',
	].join('\n');
}

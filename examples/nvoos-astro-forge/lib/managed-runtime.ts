// managed-runtime.ts — the managed deploy tier's emitted runtime files
// (Proposal 135 Phase 2).
//
// A `managed` forged site ships a Node entry beside the built `dist/`:
//
//   src/lib/managed-proxy.ts        the shared server-to-server proxy helper
//   src/pages/api/[...path].ts      /api/*  → the commerce contract
//   src/pages/api/forms/submit.ts   → the forge-bridge forms route
//   src/pages/api/revalidate.ts     token-gated, tag-based cache invalidation
//   src/pages/media/[...path].ts    /media/* → the WordPress uploads dir
//   server.js                       the Velocity entry (PM2 needs the root
//                                   entry); boots the Astro node adapter
//   scripts/sync-deploy-tree.mjs    assembles .deploy/ = dist/ + server.js +
//                                   runtime package.json for the mirror push
//
// WHY ROUTES, NOT `src/fetch.ts` (learned 2026-11-09): a custom fetch handler
// replaces Astro's request pipeline, and Astro then warns that the project's
// sessions, actions, middleware and cache handlers are NOT wired — a managed
// site would silently lose customer sessions and route caching. Endpoint
// routes run inside the normal pipeline, so everything keeps working; the
// only thing they add is the server-to-server hop.
//
// Everything here is emitted as TEXT — no WordPress credentials, no tokens.
// The operator supplies NVOOS_TARGET_SITE / NVOOS_REVALIDATE_TOKEN as
// environment variables in the Velocity app.
// ---------------------------------------------------------------------------

/** The shared proxy helper (server-to-server; cookies re-scoped host-only). */
export function renderProxyHelperTs(): string {
	return [
		'// Generated by NV oOS Astro Forge — managed proxy (Proposal 135).',
		'//',
		'// Reaches WordPress SERVER-TO-SERVER. The CMS host never needs to be',
		'// publicly reachable from a browser, so there is no CORS surface: the',
		'// browser only ever talks to this origin.',
		'',
		"const TARGET = (process.env.NVOOS_TARGET_SITE ?? '').replace(/\\/+$/, '');",
		"const PUBLIC_ORIGIN = (process.env.ASTRO_SITE ?? '').replace(/\\/+$/, '');",
		'/** The target host without its scheme — `ENOTFOUND` echoes it, so redact it. */',
		'const TARGET_HOST = (() => {',
		'\ttry {',
		'\t\treturn new URL(TARGET).host;',
		'\t} catch {',
		"\t\treturn '';",
		'\t}',
		'})();',
		'',
		'/**',
		' * How long an upstream call may take before it is abandoned (ms).',
		' *',
		' * Without a budget a hung CMS holds the Node worker until the platform',
		' * kills it. 10 s is the usual gateway default; NVOOS_PROXY_TIMEOUT_MS',
		' * overrides it inside a sane band (1 s - 60 s).',
		' */',
		'const UPSTREAM_TIMEOUT_MS = (() => {',
		'\tconst raw = Number(process.env.NVOOS_PROXY_TIMEOUT_MS);',
		'\treturn Number.isFinite(raw) && raw >= 1000 && raw <= 60000 ? raw : 10000;',
		'})();',
		'',
		'/** The CMS sets cookies for its own host; the browser must see them as',
		' *  host-only on the public origin (domain cookies are stripped). */',
		'function hostOnlyCookie(value: string): string {',
		'\treturn value.replace(/;\\s*Domain=[^;]+/gi, "");',
		'}',
		'',
		'/** Rest-param guard: no absolute paths and no traversal. */',
		'export function sanitizeRestPath(value: string | undefined): string | null {',
		"\tconst path = (value ?? '').replace(/^\\/+/, '');",
		"\tif (!path || path.includes('..')) {",
		'\t\treturn null;',
		'\t}',
		'\treturn path;',
		'}',
		'',
		'/** Remove the CMS origin AND bare host from text leaving the process. */',
		'function redactTarget(text: string): string {',
		'\tlet result = TARGET ? text.split(TARGET).join("<target>") : text;',
		'\tif (TARGET_HOST) {',
		'\t\tresult = result.split(TARGET_HOST).join("<target>");',
		'\t}',
		'\treturn result;',
		'}',
		'',
		'/** How long a CDN may keep a proxied response, in seconds. */',
		'const RELAY_MAX_AGE_SECONDS = 300;',
		'',
		'/**',
		' * Shorten a relayed Cache-Control.',
		' *',
		' * This response is re-derived on every miss, and its URL is the CMS\'s own',
		' * path — NOT content-hashed — so the bytes can change in place. Passing the',
		' * CMS\'s `max-age=31536000, immutable` through means a proxy fix cannot reach',
		' * anyone who cached the broken answer: eca\'s logo stayed a 0-byte HIT at the',
		' * edge for 49 minutes after the fix shipped, with a year left to run',
		' * (2026-11-26). Cache for minutes and let the ETag do the revalidation.',
		' */',
		'function capCacheControl(value: string): string {',
		'\tconst capped = value.replace(/\\b(s-maxage|max-age)=(\\d+)/gi, (match, name: string, seconds: string) =>',
		'\t\tNumber(seconds) > RELAY_MAX_AGE_SECONDS ? `${name}=${RELAY_MAX_AGE_SECONDS}` : match,',
		'\t);',
		'\t// `immutable` promises these bytes never change at this URL. They can.',
		'\treturn capped.replace(/,\\s*immutable\\b/gi, "").replace(/\\bimmutable\\s*,\\s*/gi, "");',
		'}',,
		'',
		'/**',
		' * Why an upstream call failed, in the form an operator can act on:',
		' * `TypeError: fetch failed <- ECONNRESET`. Node puts the actionable code on',
		' * `cause`, never on `message`, so a bare String(error) says nothing.',
		' */',
		'function describeFailure(error: unknown): string {',
		'\tlet text = error instanceof Error ? `${error.name}: ${error.message}` : String(error);',
		'\tlet cause: unknown = (error as { cause?: unknown } | null)?.cause;',
		'\tfor (let depth = 0; cause && depth < 3; depth += 1) {',
		'\t\tconst node = cause as { code?: string; message?: string; cause?: unknown };',
		'\t\ttext += ` <- ${node.code ?? node.message ?? String(cause)}`;',
		'\t\tcause = node.cause;',
		'\t}',
		'\treturn redactTarget(text);',
		'}',
		'',
		'/** A typed gateway failure — never a bare 500, and never a bare message. */',
		'function proxyFailure(code: string, status: number, message: string, targetPath: string, detail?: string): Response {',
		'\treturn Response.json({ ok: false, code, message, path: targetPath, detail }, { status });',
		'}',
		'',
		'export async function proxyToWordPress(',
		'\trequest: Request,',
		'\ttargetPath: string,',
		'\toptions: { authorization?: string } = {}',
		'): Promise<Response> {',
		'\tif (!TARGET) {',
		"\t\treturn new Response('NVOOS_TARGET_SITE is not configured.', { status: 503 });",
		'\t}',
		'',
		'\tconst url = new URL(request.url);',
		'\t// Forward ONLY what the CMS needs. Copied wholesale, the inbound request',
		'\t// carries hop-by-hop headers (connection, content-length) and the edge\'s',
		'\t// own cf-* / x-forwarded-* / cdn-loop — a CDN treats those as a spoofed',
		'\t// request and may answer 403 or reset the connection, which surfaces here',
		'\t// as "unreachable" (2026-11-26: every upload 502\'d from the Velocity node',
		'\t// while the same URL fetched fine from a workstation).',
		'\tconst FORWARDED_HEADERS = [',
		'\t\t"accept",',
		'\t\t"accept-language",',
		'\t\t"authorization",',
		'\t\t"content-type",',
		'\t\t"cookie",',
		'\t\t"referer",',
		'\t\t"user-agent",',
		'\t];',
		'\tconst headers = new Headers();',
		'\tfor (const name of FORWARDED_HEADERS) {',
		'\t\tconst value = request.headers.get(name);',
		'\t\tif (value) {',
		'\t\t\theaders.set(name, value);',
		'\t\t}',
		'\t}',
		'\t// A same-origin browser request becomes a server-to-server call.',
		'\tif (PUBLIC_ORIGIN) {',
		"\t\theaders.set('origin', PUBLIC_ORIGIN);",
		'\t}',
		'\t// §7b — a manage-scoped call carries the credential the BFF holds. It',
		'\t// REPLACES any inbound Authorization header: the browser never supplies',
		'\t// one, and a client-supplied one must not be able to impersonate the',
		'\t// manager\'s sealed credential.',
		'\tif ( options.authorization ) {',
		"\t\theaders.set( 'authorization', options.authorization );",
		'\t}',
		'\t// Ask for an uncompressed body. The runtime negotiates compression on its',
		'\t// own and then DECODES what it asked for, which would force the framing',
		'\t// strip below; identity keeps Content-Length truthful and costs nothing',
		'\t// on a hop a CDN fronts anyway.',
		"\theaders.set('accept-encoding', 'identity');",
		'',
		'\tconst init: RequestInit = { method: request.method, headers, redirect: "manual" };',
		"\tif (request.method !== 'GET' && request.method !== 'HEAD') {",
		'\t\tinit.body = await request.arrayBuffer();',
		'\t}',
		'',
		'\tlet upstream: Response;',
		'\ttry {',
		'\t\tupstream = await fetch(`${TARGET}${targetPath}${url.search}`, {',
		'\t\t\t...init,',
		'\t\t\tsignal: AbortSignal.timeout(UPSTREAM_TIMEOUT_MS),',
		'\t\t});',
		'\t} catch (error) {',
		'\t\t// RFC 9110: no timely answer is 504 (15.6.5), no valid answer at all',
		'\t\t// is 502 (15.6.3). Both carry a code, so a caller — the forms',
		'\t\t// fallback — can decide without parsing prose, and neither ever',
		'\t\t// surfaces as an unhandled 500.',
		'\t\tconst timedOut = error instanceof Error && (error.name === "TimeoutError" || error.name === "AbortError");',
		'\t\tconsole.error(`[proxy] ${targetPath}: ${timedOut ? "timeout" : "unreachable"} after ${UPSTREAM_TIMEOUT_MS} ms (${String(error)})`);',
		'\t\treturn timedOut',
		'\t\t\t? proxyFailure("upstream_timeout", 504, `The CMS did not answer within ${UPSTREAM_TIMEOUT_MS} ms.`, targetPath, describeFailure(error))',
		'\t\t\t: proxyFailure("upstream_unreachable", 502, "The CMS could not be reached.", targetPath, describeFailure(error));',
		'\t}',
		'\tconst responseHeaders = new Headers(upstream.headers);',
		'\t// The body we hand on has already been DECODED, but upstream\'s framing',
		'\t// headers describe the encoded bytes it sent. Relayed untouched, they label',
		'\t// plain text as gzip and the browser decodes it to nothing — eca\'s logo',
		'\t// loaded at 0px while `curl` showed a healthy 43 KB (2026-11-26). Strip the',
		'\t// framing for exactly the encodings the runtime decodes; an encoding it',
		'\t// passes through untouched keeps its own headers.',
		'\tconst DECODED_BY_FETCH = /^(?:gzip|x-gzip|deflate|br|zstd)$/i;',
		'\tconst encoding = (upstream.headers.get("content-encoding") ?? "").trim();',
		'\tif (DECODED_BY_FETCH.test(encoding)) {',
		"\t\tresponseHeaders.delete('content-encoding');",
		"\t\tresponseHeaders.delete('content-length');",
		'\t}',
		'\tresponseHeaders.delete(\'transfer-encoding\');',
		'\tconst cacheControl = responseHeaders.get("cache-control");',
		'\tif (cacheControl) {',
		'\t\tresponseHeaders.set("cache-control", capCacheControl(cacheControl));',
		'\t}',
		'\t// A credential-scoped answer is NOT public. The upstream marks a GET',
		'\t// cacheable for anonymous readers; passing that through would let an edge',
		'\t// hand a manager\'s draft listing to the next visitor.',
		'\tif (options.authorization) {',
		'\t\tresponseHeaders.set("cache-control", "private, no-store, max-age=0");',
		'\t}',
		'\tconst getSetCookie = (upstream.headers as Headers & { getSetCookie?: () => string[] }).getSetCookie;',
		'\tconst cookies = typeof getSetCookie === "function" ? getSetCookie.call(upstream.headers) : [];',
		'\tif (cookies.length) {',
		"\t\tresponseHeaders.delete('set-cookie');",
		'\t\tfor (const cookie of cookies) {',
		"\t\t\tresponseHeaders.append('set-cookie', hostOnlyCookie(cookie));",
		'\t\t}',
		'\t}',
		'',
		'\treturn new Response(upstream.body, {',
		'\t\tstatus: upstream.status,',
		'\t\tstatusText: upstream.statusText,',
		'\t\theaders: responseHeaders,',
		'\t});',
		'}',
		'',
	].join('\n');
}

/**
 * `/api/*` → the `nvoos-commerce/v1` contract.
 *
 * `manageCredentials` is the §7b variant: when the browser carries a valid
 * `/manage` session, the sealed Application Password is attached to the
 * upstream call. Everything else about the proxy is unchanged, so a site
 * without the opt-in emits exactly the bytes it emitted before.
 */
export interface ApiProxyOptions {
	/** Attach the manager's sealed credential when a manage session is present. */
	manageCredentials?: boolean;
}

export function renderApiProxyTs( options: ApiProxyOptions = {} ): string {
	const credentialImport = options.manageCredentials
		? "import { manageAuthorization } from '../../lib/manage-credential';"
		: '';
	const forward = options.manageCredentials
		? [
				'\t// The browser holds no credential: the BFF decrypts the sealed cookie',
				'\t// and authorises the upstream call. An anonymous request forwards none.',
				"\tconst authorization = manageAuthorization(request.headers.get('cookie'));",
				'\treturn proxyToWordPress(',
				'\t\trequest,',
				'\t\t`/wp-json/nvoos-commerce/v1/${rest}`,',
				'\t\tauthorization ? { authorization } : undefined',
				'\t);',
		  ].join( '\n' )
		: '\treturn proxyToWordPress(request, `/wp-json/nvoos-commerce/v1/${rest}`);';

	return [
		'// Generated by NV oOS Astro Forge — commerce API proxy (Proposal 135).',
		'//',
		'//   /api/products            → <CMS>/wp-json/nvoos-commerce/v1/products',
		'//   /api/auth/login          → <CMS>/wp-json/nvoos-commerce/v1/auth/login',
		'//   /api/globals/shop        → <CMS>/wp-json/nvoos-commerce/v1/globals/shop',
		'//',
		'// Static routes win over this rest param, so /api/revalidate and',
		'// /api/forms/submit are never proxied.',
		"import type { APIRoute } from 'astro';",
		"import { proxyToWordPress, sanitizeRestPath } from '../../lib/managed-proxy';",
		...( credentialImport ? [ credentialImport ] : [] ),
		'',
		'export const prerender = false;',
		'',
		'export const ALL: APIRoute = async ({ params, request }) => {',
		'\tconst rest = sanitizeRestPath(params.path);',
		'\tif (rest === null) {',
		"\t\treturn new Response('Not found', { status: 404 });",
		'\t}',
		forward,
		'};',
		'',
	].join('\n');
}

/**
 * The `/api/forms/submit` route with a direct fallback (`forms.fallback`).
 *
 * Kept out of the default emitter so a bridge site without the opt-in ships
 * exactly the bytes it shipped before.
 */
function renderFormsFallbackTs(): string {
	return [
		'// Generated by NV oOS Astro Forge — forms proxy with a DIRECT fallback.',
		'//',
		'// The bridge stays authoritative: WordPress owns the handler, its side',
		'// effects and its mailer. When the bridge cannot take the submission',
		'// (unreachable, timeout, 5xx) the SAME payload is delivered through the',
		'// provider API instead, so an outage costs no enquiry.',
		'//',
		'// A 4xx is an answer, not a fault: a validation rejection or the bridge',
		'// throttle must reach the visitor untouched. So must a 501 (bridge',
		'// present, no handler) — masking it would hide the fault worth fixing.',
		"import type { APIRoute } from 'astro';",
		"import { proxyToWordPress } from '../../../lib/managed-proxy';",
		"import { readMailConfig, runtimeEnv, sendMail } from '../../../forge/mail.ts';",
		"import { readSubmissionFields, submissionMessage } from '../../../forge/forms.ts';",
		'',
		'export const prerender = false;',
		'',
		'/** The bridge route. */',
		"const BRIDGE_PATH = '/wp-json/nvoos-forge/v1/forms/submit';",
		'/** Consecutive bridge failures that open the breaker. */',
		'const BREAKER_THRESHOLD = 3;',
		'/** How long the breaker stays open before one probe is allowed (ms). */',
		'const BREAKER_OPEN_MS = 60_000;',
		'',
		'/**',
		' * Breaker state.',
		' *',
		' * A timeout bounds ONE call; it does not stop a sustained outage from',
		' * costing every visitor the full budget and draining the worker pool.',
		' * After BREAKER_THRESHOLD consecutive failures the bridge is skipped for',
		' * BREAKER_OPEN_MS, then a single probe decides: success closes the',
		' * breaker, failure re-opens it.',
		' */',
		'let bridgeFailures = 0;',
		'let bridgeOpenUntil = 0;',
		'',
		'/**',
		' * Deliver the submission through the provider API.',
		' *',
		' * The message (reserved fields, Reply-To, idempotency digest) comes from',
		' * the same module the direct endpoint uses, so the two paths cannot',
		' * drift. The no-JS floor gets JSON here rather than the bridge redirect:',
		' * that redirect is validated against an allowlist on the WordPress side,',
		' * and reproducing it here would duplicate the open-redirect guard.',
		' */',
		'async function deliverDirect( request: Request, reason: string ): Promise< Response > {',
		'\tconst fields = await readSubmissionFields( request );',
		'\tif ( ! fields ) {',
		"\t\treturn new Response( 'Bad request', { status: 400 } );",
		'\t}',
		'\tconst message = submissionMessage( fields );',
		'\tif ( ! message ) {',
		"\t\treturn new Response( 'Empty submission', { status: 400 } );",
		'\t}',
		'\tconsole.warn( `[forms] direct fallback (${ reason }) — the bridge did not take the submission` );',
		'\tconst result = await sendMail( readMailConfig( runtimeEnv() ), message );',
		'\tif ( ! result.ok ) {',
		'\t\tconsole.error( `[forms] fallback delivery failed (${ result.status }): ${ result.detail ?? "" }` );',
		"\t\treturn new Response( 'Delivery failed', { status: 502 } );",
		'\t}',
		'\treturn Response.json( { ok: true } );',
		'}',
		'',
		'export const ALL: APIRoute = async ( { request } ) => {',
		'\t// Only a submission can be re-delivered; other methods proxy untouched.',
		'\tif ( request.method !== "POST" ) {',
		'\t\treturn proxyToWordPress( request, BRIDGE_PATH );',
		'\t}',
		'\t// The bridge hop consumes the body, so keep a copy for a possible fallback.',
		'\tconst copy = request.clone();',
		'\tconst now = Date.now();',
		'\tif ( bridgeFailures >= BREAKER_THRESHOLD && now < bridgeOpenUntil ) {',
		'\t\treturn deliverDirect( copy, "circuit open" );',
		'\t}',
		'\tlet response: Response;',
		'\ttry {',
		'\t\tresponse = await proxyToWordPress( request, BRIDGE_PATH );',
		'\t} catch ( error ) {',
		'\t\tconsole.error( `[forms] bridge threw: ${ String( error ) }` );',
		'\t\treturn deliverDirect( copy, "bridge threw" );',
		'\t}',
		'\tif ( response.status < 500 || response.status === 501 ) {',
		'\t\t// 2xx/3xx/4xx is the bridge answer — including its throttle and its',
		'\t\t// validation errors. So is a 501: the bridge IS there but has no',
		'\t\t// handler, which is a configuration fault worth surfacing rather than',
		'\t\t// masking with a fallback. Resetting here closes a half-open breaker.',
		'\t\tbridgeFailures = 0;',
		'\t\treturn response;',
		'\t}',
		'\tbridgeFailures += 1;',
		'\tif ( bridgeFailures >= BREAKER_THRESHOLD ) {',
		'\t\tbridgeOpenUntil = now + BREAKER_OPEN_MS;',
		'\t\tconsole.warn( `[forms] breaker open for ${ BREAKER_OPEN_MS } ms after ${ bridgeFailures } bridge failure(s)` );',
		'\t}',
		'\treturn deliverDirect( copy, `bridge ${ response.status }` );',
		'};',
		'',
	].join( '\n' );
}

/** `forms.fallback` — deliver through the provider when the bridge fails. */
export interface FormsProxyOptions {
	fallback?: 'direct';
}

/**
 * `/api/forms/submit` → the forge-bridge forms route.
 *
 * With `forms.fallback: 'direct'` the bridge stays authoritative, but a
 * submission it cannot take (unreachable, timeout, 5xx) is delivered through
 * the provider instead — a CMS outage then costs no enquiry.
 */
export function renderFormsProxyTs( options: FormsProxyOptions = {} ): string {
	if ( options.fallback === 'direct' ) {
		return renderFormsFallbackTs();
	}
	return [
		'// Generated by NV oOS Astro Forge — forms proxy (Proposal 135).',
		'//',
		'// The rebuilt forms POST here; the request continues server-to-server to',
		'// the forge bridge, which runs the JetFormBuilder / Elementor handler.',
		"import type { APIRoute } from 'astro';",
		"import { proxyToWordPress } from '../../../lib/managed-proxy';",
		'',
		'export const prerender = false;',
		'',
		'export const ALL: APIRoute = async ({ request }) =>',
		"\tproxyToWordPress(request, '/wp-json/nvoos-forge/v1/forms/submit');",
		'',
	].join('\n');
}


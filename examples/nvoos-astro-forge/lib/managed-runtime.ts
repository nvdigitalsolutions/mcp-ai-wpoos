/**
 * `/api/preview` — the token exchange (Proposal 135 Phase 5).
 *
 * `/manage` mints a short-lived token on the CMS and hands the editor this
 * URL. The route stores the token in a HOST-ONLY cookie and redirects to the
 * draft-aware SSR page. It never verifies the token — the same tokens are
 * verified by the bridge, so the frontend holds no key material and cannot
 * mint one.
 */
export function renderPreviewApiTs(): string {
	return [
		'// Generated by NV oOS Astro Forge — preview exchange (Proposal 135).',
		'//',
		'// GET /api/preview?token=<bridge token>&slug=<slug>',
		'//   → Set-Cookie: nvoos_preview=<token>; HttpOnly; SameSite=Lax; Path=/',
		'//   → 302 /preview/<slug>/',
		'//',
		'// No Domain attribute on purpose: the cookie is host-only, so it works on',
		'// this site and is never sent to the CMS host.',
		"import type { APIRoute } from 'astro';",
		'',
		"const COOKIE = 'nvoos_preview';",
		"const MAX_AGE = 900;",
		'',
		'/** Only a plain slug is accepted — never a path or an absolute URL. */',
		'function safeSlug(value: string | null): string | null {',
		'\tconst slug = (value ?? \'\').trim();',
		"\treturn /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) ? slug : null;",
		'}',
		'',
		'export const prerender = false;',
		'',
		'export const GET: APIRoute = async ({ url, cookies, redirect }) => {',
		"\tconst token = url.searchParams.get('token') ?? '';",
		"\tconst slug = safeSlug(url.searchParams.get('slug'));",
		'\tif (!token || !slug) {',
		"\t\treturn new Response('Preview link is incomplete.', { status: 400 });",
		'\t}',
		'',
		'\tcookies.set(COOKIE, token, {',
		"\t\tpath: '/',",
		'\t\thttpOnly: true,',
		"\t\tsameSite: 'lax',",
		"\t\tsecure: url.protocol === 'https:',",
		'\t\tmaxAge: MAX_AGE,',
		'\t});',
		'',
		'\tconst response = redirect(`/preview/${slug}/`, 302);',
		"\tresponse.headers.set('cache-control', 'no-store');",
		'\treturn response;',
		'};',
		'',
	].join('\n');
}


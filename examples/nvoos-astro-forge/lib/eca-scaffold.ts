// eca-scaffold.ts — the ECA preset's generated artifacts (Proposal 163 §P1).
//
// Kept out of `scaffold.ts` on purpose: the scaffold is the composition root and
// is already large, while everything here is a pure function of the profile.
//
// Two artifacts:
//
//   src/forge/eca.ts            the `nvoos-eca/v1` normaliser, vendored so the
//                               customer repo builds standalone (it is copied
//                               ONLY when the profile declares `eca`, unlike the
//                               always-vendored libs in FORGE_LIB_FILES)
//   src/lib/eca.generated.ts    this site's config: stages, terms, currency,
//                               time bands, the catalogue path and the
//                               registration hand-off
//
// The generated module also carries the taxonomy reader. Categories are the one
// ECA fact that does not travel on the record — `mcp_ai_eca_category` is a list
// of ids, and a card that renders "36" instead of "Arts & Music" is a bug, so
// the names are fetched once per build and cached in module scope.
// ---------------------------------------------------------------------------

import type { SiteProfile } from './types.ts';
import { ECA_COLLECTION, ECA_PROFILE_DEFAULTS } from './presets.ts';
import { normalizeBasePath } from './eca.ts';

/** Path of the generated config module, relative to the project root. */
export const ECA_CONFIG_PATH = 'src/lib/eca.generated.ts';

/** Path of the vendored normaliser, relative to the project root. */
export const ECA_VENDORED_PATH = 'src/forge/eca.ts';

/**
 * The taxonomy REST base for a CPT base.
 *
 * The toolkit registers `mcp_ai_eca_category` alongside the `mcp_ai_eca` post
 * type, so the suffix is derivable. An operator can override it on the profile
 * collection (`taxonomyRestBase`) when a site renamed the taxonomy.
 */
export function deriveTaxonomyRestBase( restBase: string ): string {
	if ( ! restBase.startsWith( 'wp/v2/' ) ) return '';
	const postType = restBase.slice( 'wp/v2/'.length );
	return postType ? 'wp/v2/' + postType + '_category' : '';
}

/** The collection the ECA preset ensures, or the profile's own activities entry. */
export function ecaCollection( profile: SiteProfile ) {
	return (
		profile.collections.find( ( collection ) =>
			collection.slug === ECA_COLLECTION.slug || /^wp\/v2\/mcp_ai_eca$/.test( collection.restBase ),
		) ?? ECA_COLLECTION
	);
}

/**
 * Warnings an ECA profile needs before it builds.
 *
 * Every line is a real launch trap: an ICS feed is withheld without terms, and
 * a register button without a URL renders as copy — both are correct behaviour
 * but silently surprising, so the operator is told at scaffold time.
 */
export function ecaScaffoldWarnings( profile: SiteProfile ): string[] {
	const eca = profile.eca;
	if ( ! eca ) return [];
	const warnings: string[] = [];

	if ( ! eca.terms || eca.terms.length === 0 ) {
		warnings.push(
			'ECA: no `eca.terms` — every .ics feed is withheld (a recurring event needs a term end). Add terms to light them up.',
		);
	}
	if ( ! eca.timezone ) {
		warnings.push( 'ECA: no `eca.timezone` — calendar times default to UTC; set the school zone (e.g. Asia/Colombo).' );
	}
	if ( ! eca.currency ) {
		warnings.push( 'ECA: no `eca.currency` — pricing defaults to LKR (the donor site). Set the ISO code for this school.' );
	}
	if ( ! eca.booking?.urlTemplate && ! eca.booking?.url ) {
		warnings.push(
			'ECA: no `eca.booking.urlTemplate` — the register CTA renders as instructions rather than a link. Add a template ({slug}/{id}/{code}) to enable it.',
		);
	}
	if ( ! eca.stages || eca.stages.length === 0 ) {
		warnings.push( 'ECA: no `eca.stages` — falling back to junior-school / senior-school (years 1-6 / 7-13).' );
	}
	return warnings;
}

/** Render `src/lib/eca.generated.ts`. */
export function renderEcaGenerated( profile: SiteProfile ): string {
	const collection = ecaCollection( profile );
	const eca = { ...ECA_PROFILE_DEFAULTS, ...( profile.eca ?? {} ) };
	const basePath = normalizeBasePath( eca.basePath ?? ECA_COLLECTION.basePath ?? '/activities' );
	const sourceOrigin = profile.url.replace( /\/+$/, '' );
	const taxonomyRestBase = deriveTaxonomyRestBase( collection.restBase );
	const termsRestBase = ( profile.eca as { taxonomyRestBase?: string } | undefined )?.taxonomyRestBase ?? taxonomyRestBase;

	const config = { ...eca, basePath };
	for ( const key of Object.keys( config ) as Array< keyof typeof config > ) {
		if ( config[ key ] === undefined ) delete config[ key ];
	}

	return [
		'// eca.generated.ts — generated by nvoos-astro-forge (Proposal 163);',
		'// edits here are overwritten on re-scaffold. The site config lives on the',
		'// forge profile (`eca:`), not in this file.',
		"import { htmlDecode, type EcaTermMap, type ForgeEca } from '../forge/eca.ts';",
		'',
		'/** This site\'s ECA configuration — stages, terms, currency, hand-off. */',
		'export const ecaConfig: ForgeEca = ' + JSON.stringify( config, null, '\t' ) + ';',
		'',
		'/** Catalogue URL prefix. */',
		'export const ecaBasePath = ' + JSON.stringify( basePath ) + ';',
		'',
		'/** The CMS origin records are READ from — never the public origin. */',
		'export const ecaSourceOrigin = ' + JSON.stringify( sourceOrigin ) + ';',
		'',
		'/** REST base of the activity collection. */',
		'export const ecaRestBase = ' + JSON.stringify( collection.restBase ) + ';',
		'',
		'/** REST base of the category taxonomy (empty when not derivable). */',
		'export const ecaTaxonomyRestBase = ' + JSON.stringify( termsRestBase ) + ';',
		'',
		'let termsPromise: Promise< EcaTermMap > | null = null;',
		'',
		'/**',
		' * Category id → name, fetched once per build.',
		' *',
		' * A failure degrades to NO labels (the facet then renders the taxonomy as',
		' * unknown rather than as bare ids) and is logged — a missing label must never',
		' * fail a build, but it must never be silent either.',
		' */',
		'export function ecaTerms(): Promise< EcaTermMap > {',
		'\tif ( ! termsPromise ) {',
		'\t\ttermsPromise = ( async () => {',
		'\t\t\tif ( ! ecaTaxonomyRestBase ) return [];',
		'\t\t\tconst username = import.meta.env.WP_APPLICATION_USER;',
		'\t\t\tconst password = import.meta.env.WP_APPLICATION_PASSWORD;',
		'\t\t\tconst headers: Record< string, string > = { accept: "application/json" };',
		'\t\t\tif ( username && password ) {',
		'\t\t\t\theaders.authorization = "Basic " + Buffer.from( username + ":" + password ).toString( "base64" );',
		'\t\t\t}',
		'\t\t\ttry {',
		'\t\t\t\tconst response = await fetch( ecaSourceOrigin + "/wp-json/" + ecaTaxonomyRestBase + "?per_page=100&_fields=id,name,slug", { headers } );',
		'\t\t\t\tif ( ! response.ok ) {',
		'\t\t\t\t\tconsole.warn( "[eca] taxonomy " + ecaTaxonomyRestBase + " answered " + response.status + " — category labels are unavailable." );',
		'\t\t\t\t\treturn [];',
		'\t\t\t\t}',
		'\t\t\t\tconst body = ( await response.json() ) as Array< { id?: number; name?: string; slug?: string } >;',
		'\t\t\t\treturn body',
		'\t\t\t\t\t.filter( ( term ) => typeof term.id === "number" && typeof term.name === "string" && typeof term.slug === "string" )',
		'\t\t\t\t\t.map( ( term ) => ( { id: term.id as number, name: htmlDecode( term.name as string ), slug: term.slug as string } ) );',
		'\t\t\t} catch ( error ) {',
		'\t\t\t\tconsole.warn( "[eca] taxonomy fetch failed — category labels are unavailable: " + String( error ) );',
		'\t\t\t\treturn [];',
		'\t\t\t}',
		'\t\t} )();',
		'\t}',
		'\treturn termsPromise;',
		'}',
		'',
	].join( '\n' );
}

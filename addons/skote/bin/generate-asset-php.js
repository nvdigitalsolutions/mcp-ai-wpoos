#!/usr/bin/env node
/**
 * bin/generate-asset-php.js
 *
 * Reads `dist/manifest.json` produced by Vite and writes a
 * `dist/index.asset.php` file shaped like the one `@wordpress/scripts`
 * emits, so `class-nvoos-skote-assets.php` can pick up the correct
 * dependency list and version hash via the standard PHP enqueue pattern.
 *
 * Output shape:
 *
 *   <?php return array(
 *       'dependencies' => array(),
 *       'version'      => 'abcd1234',
 *   );
 *
 * Run automatically via `npm run build` after `vite build`.
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const distDir = path.resolve(__dirname, '..', 'dist');

function hashFile(file) {
	const hash = crypto.createHash('sha256');
	hash.update(fs.readFileSync(file));
	return hash.digest('hex').slice(0, 20);
}

function main() {
	const indexJs = path.join(distDir, 'index.js');
	if (!fs.existsSync(indexJs)) {
		console.error(`❌ ${indexJs} not found. Run 'vite build' first.`);
		process.exit(1);
	}

	const version = hashFile(indexJs);
	const dependencies = []; // Phase 1: SPA bundles its own React + ReactDOM.

	const php =
		"<?php\n" +
		"// Auto-generated by bin/generate-asset-php.js — do not edit.\n" +
		"return array(\n" +
		"\t'dependencies' => array(" +
		dependencies.map((d) => `'${d.replace(/'/g, "\\'")}'`).join(', ') +
		"),\n" +
		`\t'version'      => '${version}',\n` +
		');\n';

	fs.writeFileSync(path.join(distDir, 'index.asset.php'), php, 'utf8');
	console.log(`✅ Wrote dist/index.asset.php (version ${version})`);
}

main();

/**
 * GTmetrix → WPCode bridge.
 *
 * @since 1.2.5
 */
class WP_MCP_AI_GTmetrix_WPCode_Bridge {

	const TAG = 'gtmetrix-fix';

	/**
	 * Install matched fixes as an inactive WPCode draft.
	 *
	 * @param array $fixes     Matched fix records (fix engine output).
	 * @param array $context   Context: report_id, url, title.
	 * @return array|WP_Error   snippet_id + admin edit URL.
	 */
	public function install_draft( $fixes, $context = array() ) {
		$repository = new WP_MCP_AI_Pro_WPCode_Snippet_Repository();
		if ( ! $repository->is_available() ) {
			return new WP_Error( 'wp_mcp_ai_wpcode_missing', __( 'WPCode must be installed and active to install fix snippets.', 'mcp-ai-wpoos-pro' ) );
		}

		$code = WP_MCP_AI_GTmetrix_Fix_Engine::generate_snippet( $fixes, $context );
		if ( '' === trim( $code ) ) {
			return new WP_Error( 'wp_mcp_ai_gtmetrix_no_code', __( 'No code blocks matched the selected fixes; nothing to install.', 'mcp-ai-wpoos-pro' ) );
		}

		$report_id = isset( $context['report_id'] ) ? sanitize_text_field( $context['report_id'] ) : '';
		$title     = isset( $context['title'] ) ? sanitize_text_field( $context['title'] ) : __( 'GTmetrix performance fixes', 'mcp-ai-wpoos-pro' );
		$note      = sprintf(
			/* translators: %s: GTmetrix report ID */
			__( 'Generated by the GTmetrix toolkit from report %s. Test on staging, then activate blocks one at a time.', 'mcp-ai-wpoos-pro' ),
			$report_id
		);

		$data = array(
			'code'        => $code,
			'code_type'   => 'php',
			'auto_insert' => 1,
			'location'    => 'everywhere',
			'title'       => $title,
			'active'      => false, // Drafts only — activation is a human step.
			'tags'        => array( self::TAG ),
			'note'        => $note,
		);

		$result = $repository->save( $data );
		if ( is_wp_error( $result ) ) {
			return $result;
		}

		return array(
			'snippet_id' => $result,
			'title'      => $title,
			'active'     => false,
			'tags'       => array( self::TAG ),
			'admin_url'  => admin_url( 'admin.php?page=wpcode-snippet-manager&wpcode-edit=' . absint( $result ) ),
			'report_id'  => $report_id,
		);
	}

	/**
	 * Suggested Smart Conditional Logic groups for a fix (manual-paste fallback).
	 *
	 * @param array $fix Fix record.
	 * @return array
	 */
	public function suggested_conditional_logic( $fix ) {
		$conditional = isset( $fix['conditional'] ) && is_array( $fix['conditional'] ) ? $fix['conditional'] : array();
		if ( empty( $conditional ) ) {
			return array();
		}

		return array( $conditional );
	}
}

					'args'                => array(
						'assistant_id'  => array(
							'description'       => __( 'Assistant ID to stream notifications for.', 'wp-mcp-ai' ),
							'type'              => 'integer',
							'required'          => true,
							'validate_callback' => function( $param ) {

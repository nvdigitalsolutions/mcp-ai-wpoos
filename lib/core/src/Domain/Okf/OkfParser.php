<?php
/**
 * Markdown + YAML frontmatter parser for OKF concepts.
 *
 * Implements the subset of YAML that OKF frontmatter actually uses: scalars,
 * block sequences, nested mappings, lists of objects, and the inline
 * `{ ... }` / `[ ... ]` forms. It is deliberately not a YAML processor —
 * anchors, block scalars, multi-document streams and merge keys are out of
 * scope, which the format specification permits.
 *
 * Framework-neutral by construction: the only inputs are the document text
 * and the only outputs are an OkfDocument or null. There is no filesystem
 * access, no WordPress call, and no global state.
 *
 * Extracted from `WP_MCP_AI_OKF_Parser` under Proposal 145. Behaviour is
 * pinned by the shared golden corpus in `tests/fixtures/okf/parser/`, which
 * both implementations replay, so this class may not drift from the
 * WordPress original without failing a test.
 *
 * State note: the recursive-descent loop keeps its cursor on the instance,
 * so a single instance must not parse two documents concurrently. That
 * mirrors the original and is safe for sequential use.
 *
 * @package Nvoos\Core
 * @since   1.4.0
 * @license MIT
 *
 * SPDX-License-Identifier: MIT
 */

declare(strict_types=1);

namespace Nvoos\Core\Domain\Okf;

final class OkfParser implements OkfParserInterface {

	/**
	 * Recognises a frontmatter key line.
	 *
	 * Keys are word characters plus interior spaces, which covers the OKF
	 * vocabulary (`stale_after`, `generated by`) without accepting YAML
	 * syntax the parser cannot handle.
	 */
	private const KEY_PATTERN = '/^(\w[\w\s]*?):\s*(.*)$/';

	/**
	 * Byte-order mark. `trim()` does not treat it as whitespace.
	 */
	private const UTF8_BOM = "\xEF\xBB\xBF";

	/**
	 * Frontmatter lines for the current parse.
	 *
	 * @var list<string>
	 */
	private array $lines = array();

	/**
	 * Number of lines in the current parse.
	 */
	private int $lineCount = 0;

	/**
	 * Current cursor into {@see self::$lines}.
	 */
	private int $position = 0;

	/**
	 * {@inheritDoc}
	 */
	public function parse( string $content ): ?OkfDocument {
		$content = trim( $content );

		// A BOM survives trim(), so without this a Windows-authored file looks
		// like it has no frontmatter at all and is silently ignored.
		if ( 0 === strncmp( $content, self::UTF8_BOM, 3 ) ) {
			$content = trim( substr( $content, 3 ) );
		}

		// Frontmatter must start with --- on the first line.
		if ( 0 !== strpos( $content, '---' ) ) {
			return null;
		}

		$closingPosition = strpos( $content, '---', 3 );

		if ( false === $closingPosition ) {
			throw new OkfParseException(
				'okf_unclosed_frontmatter',
				'OKF frontmatter block is not closed with ---.'
			);
		}

		$yaml = substr( $content, 3, $closingPosition - 3 );
		$body = trim( substr( $content, $closingPosition + 3 ) );

		return new OkfDocument( $this->parseYamlBlock( $yaml ), $body );
	}

	// -------------------------------------------------------------------------
	// Parsing — indentation-aware recursive descent
	// -------------------------------------------------------------------------

	/**
	 * Parse a full YAML frontmatter block into an associative array.
	 *
	 * @param string $yaml Raw YAML between the delimiters.
	 *
	 * @return array<string, mixed>
	 */
	private function parseYamlBlock( string $yaml ): array {
		$this->lines     = explode( "\n", $yaml );
		$this->lineCount = count( $this->lines );
		$this->position  = 0;

		return $this->parseMapping( 0 );
	}

	/**
	 * Parse a mapping block at a given indentation level.
	 *
	 * Advances the cursor past every consumed line and stops at the first
	 * line indented less than `$baseIndent`, which belongs to a parent block.
	 *
	 * @param int $baseIndent Expected indentation for keys in this block.
	 *
	 * @return array<string, mixed>
	 */
	private function parseMapping( int $baseIndent ): array {
		$result = array();

		while ( $this->position < $this->lineCount ) {
			$raw     = $this->lines[ $this->position ];
			$trimmed = rtrim( $raw );
			$indent  = $this->getIndent( $raw );

			// A line at strictly lower indentation ends this block.
			if ( '' !== $trimmed && '#' !== $trimmed[0] && $indent < $baseIndent ) {
				break;
			}

			++$this->position;

			// Skip blank lines and comment-only lines.
			if ( '' === $trimmed || '#' === $trimmed[0] ) {
				continue;
			}

			// Skip lines not at our expected indentation (they belong to a parent or sibling).
			if ( $indent !== $baseIndent ) {
				continue;
			}

			$stripped = ltrim( $trimmed );

			if ( preg_match( self::KEY_PATTERN, $stripped, $matches ) ) {
				$key   = trim( $matches[1] );
				$value = trim( $matches[2] );

				if ( '' === $value ) {
					// Empty value — resolve the indented block (list or nested mapping).
					$result[ $key ] = $this->parseBlockValue( $indent );
				} else {
					$result[ $key ] = $this->castValue( $value );
				}
			}
		}

		return $result;
	}

	/**
	 * Parse the indented value block following a `key:` with an empty value.
	 *
	 * Decides between a block sequence (items begin with `- `) and a nested
	 * mapping, based on the first content line of the block.
	 *
	 * @param int $parentIndent Indentation of the parent `key:` line.
	 *
	 * @return array<array-key, mixed>
	 */
	private function parseBlockValue( int $parentIndent ): array {
		$peek         = $this->position;
		$nextStripped = '';
		$nextIndent   = -1;

		while ( $peek < $this->lineCount ) {
			$raw     = $this->lines[ $peek ];
			$trimmed = rtrim( $raw );

			if ( '' !== $trimmed && '#' !== $trimmed[0] ) {
				$nextStripped = ltrim( $trimmed );
				$nextIndent   = $this->getIndent( $raw );
				break;
			}

			++$peek;
		}

		// No content, or the next content line belongs to a parent block.
		if ( -1 === $nextIndent || $nextIndent <= $parentIndent ) {
			return array();
		}

		if ( str_starts_with( $nextStripped, '- ' ) ) {
			return $this->parseList( $nextIndent, $parentIndent );
		}

		return $this->parseMapping( $nextIndent );
	}

	/**
	 * Parse a block sequence at the given indentation level.
	 *
	 * Items may be scalars, inline mappings, inline sequences, or objects
	 * whose remaining keys continue on deeper-indented lines.
	 *
	 * @param int $listIndent   Indentation of the `- ` prefix.
	 * @param int $parentIndent Indentation of the parent `key:` line.
	 *
	 * @return array<int, mixed>
	 */
	private function parseList( int $listIndent, int $parentIndent ): array {
		$items = array();

		while ( $this->position < $this->lineCount ) {
			$raw     = $this->lines[ $this->position ];
			$trimmed = rtrim( $raw );
			$indent  = $this->getIndent( $raw );

			// End of list: a content line at or above the parent indentation.
			if ( '' !== $trimmed && '#' !== $trimmed[0] && $indent <= $parentIndent ) {
				break;
			}

			++$this->position;

			if ( '' === $trimmed || '#' === $trimmed[0] ) {
				continue;
			}

			$stripped = ltrim( $trimmed );

			// Not a list item — belongs to a sibling construct.
			if ( ! str_starts_with( $stripped, '- ' ) ) {
				continue;
			}

			$itemValue = trim( substr( $stripped, 2 ) );

			// Inline mapping — `- { key: value, ... }`.
			if ( '' !== $itemValue && '{' === $itemValue[0] ) {
				$items[] = $this->parseInlineMapping( $itemValue );
				continue;
			}

			// Inline flow sequence — `- [item, item, ...]`.
			if ( '' !== $itemValue && '[' === $itemValue[0] ) {
				$items[] = $this->parseInlineSequence( $itemValue );
				continue;
			}

			// Object start — `- key: value`, possibly continued below.
			if ( preg_match( self::KEY_PATTERN, $itemValue, $matches ) ) {
				$objectKey   = trim( $matches[1] );
				$objectValue = trim( $matches[2] );
				$nested      = array();

				if ( '' === $objectValue ) {
					$nested[ $objectKey ] = $this->parseBlockValue( $indent );
				} else {
					$nested[ $objectKey ] = $this->castValue( $objectValue );
				}

				$items[] = $this->parseObjectContinuation( $nested, $indent );
				continue;
			}

			$items[] = $this->castValue( $itemValue );
		}

		return $items;
	}

	/**
	 * Collect the remaining keys of a list item that is a nested object.
	 *
	 * @param array<string, mixed> $nested     Object built so far.
	 * @param int                  $listIndent Indentation of the `- ` prefix.
	 *
	 * @return array<string, mixed>
	 */
	private function parseObjectContinuation( array $nested, int $listIndent ): array {
		while ( $this->position < $this->lineCount ) {
			$raw     = $this->lines[ $this->position ];
			$trimmed = rtrim( $raw );
			$indent  = $this->getIndent( $raw );

			if ( '' === $trimmed || '#' === $trimmed[0] ) {
				++$this->position;
				continue;
			}

			if ( $indent <= $listIndent ) {
				break;
			}

			++$this->position;

			$stripped = ltrim( $trimmed );

			if ( preg_match( self::KEY_PATTERN, $stripped, $matches ) ) {
				$key   = trim( $matches[1] );
				$value = trim( $matches[2] );

				if ( '' === $value ) {
					$nested[ $key ] = $this->parseBlockValue( $indent );
				} else {
					$nested[ $key ] = $this->castValue( $value );
				}
			}
		}

		return $nested;
	}

	// -------------------------------------------------------------------------
	// Value casting and inline constructs
	// -------------------------------------------------------------------------

	/**
	 * Cast a raw value, dispatching on the inline collection forms.
	 */
	private function castValue( string $value ): mixed {
		if ( '' !== $value && '{' === $value[0] ) {
			return $this->parseInlineMapping( $value );
		}

		if ( '' !== $value && '[' === $value[0] ) {
			return $this->parseInlineSequence( $value );
		}

		return $this->castScalar( $value );
	}

	/**
	 * Parse an inline mapping: `{ key1: value1, key2: value2 }`.
	 *
	 * @param string $raw Raw mapping string, with or without outer braces.
	 *
	 * @return array<string, mixed>
	 */
	private function parseInlineMapping( string $raw ): array {
		$raw = trim( $raw );

		if ( '' !== $raw && '{' === $raw[0] ) {
			$raw = substr( $raw, 1 );
		}

		$length = strlen( $raw );

		if ( $length > 0 && '}' === $raw[ $length - 1 ] ) {
			$raw = substr( $raw, 0, -1 );
		}

		if ( '' === trim( $raw ) ) {
			return array();
		}

		$result = array();

		foreach ( $this->splitInlinePairs( $raw ) as $pair ) {
			$colon = $this->findTopLevelColon( $pair );

			if ( false === $colon ) {
				continue;
			}

			$key   = trim( substr( $pair, 0, $colon ) );
			$value = trim( substr( $pair, $colon + 1 ) );

			$result[ $key ] = $this->castValue( $value );
		}

		return $result;
	}

	/**
	 * Parse an inline flow sequence: `[ item1, item2, item3 ]`.
	 *
	 * @param string $raw Raw sequence string, with or without outer brackets.
	 *
	 * @return array<int, mixed>
	 */
	private function parseInlineSequence( string $raw ): array {
		$raw = trim( $raw );

		if ( '' !== $raw && '[' === $raw[0] ) {
			$raw = substr( $raw, 1 );
		}

		$length = strlen( $raw );

		if ( $length > 0 && ']' === $raw[ $length - 1 ] ) {
			$raw = substr( $raw, 0, -1 );
		}

		if ( '' === trim( $raw ) ) {
			return array();
		}

		$result = array();

		foreach ( $this->splitInlinePairs( $raw ) as $item ) {
			$result[] = $this->castValue( trim( $item ) );
		}

		return $result;
	}

	/**
	 * Split on top-level commas, respecting nested braces and brackets.
	 *
	 * @param string $raw String to split.
	 *
	 * @return list<string>
	 */
	private function splitInlinePairs( string $raw ): array {
		$pairs  = array();
		$depth  = 0;
		$buffer = '';
		$length = strlen( $raw );

		for ( $i = 0; $i < $length; $i++ ) {
			$char = $raw[ $i ];

			if ( '{' === $char || '[' === $char ) {
				++$depth;
				$buffer .= $char;
			} elseif ( '}' === $char || ']' === $char ) {
				--$depth;
				$buffer .= $char;
			} elseif ( ',' === $char && 0 === $depth ) {
				$pairs[] = trim( $buffer );
				$buffer  = '';
			} else {
				$buffer .= $char;
			}
		}

		if ( '' !== trim( $buffer ) ) {
			$pairs[] = trim( $buffer );
		}

		return $pairs;
	}

	/**
	 * Find the first colon that is not nested inside braces or brackets.
	 *
	 * @param string $pair Pair string, e.g. `by: reference_agent/gemini`.
	 */
	private function findTopLevelColon( string $pair ): int|false {
		$depth  = 0;
		$length = strlen( $pair );

		for ( $i = 0; $i < $length; $i++ ) {
			$char = $pair[ $i ];

			if ( '{' === $char || '[' === $char ) {
				++$depth;
			} elseif ( '}' === $char || ']' === $char ) {
				--$depth;
			} elseif ( ':' === $char && 0 === $depth ) {
				return $i;
			}
		}

		return false;
	}

	/**
	 * Cast a YAML scalar to the appropriate PHP type.
	 *
	 * Quoted values stay strings so `'0042'` does not become 42 and
	 * `'true'` does not become a boolean.
	 */
	private function castScalar( string $value ): mixed {
		if ( preg_match( '/^(["\'])(.*)\1$/', $value, $matches ) ) {
			return $matches[2];
		}

		$lower = strtolower( $value );

		if ( 'true' === $lower ) {
			return true;
		}

		if ( 'false' === $lower ) {
			return false;
		}

		if ( 'null' === $lower || '~' === $value ) {
			return null;
		}

		if ( preg_match( '/^-?\d+$/', $value ) ) {
			return (int) $value;
		}

		if ( preg_match( '/^-?\d+\.\d+$/', $value ) ) {
			return (float) $value;
		}

		return $value;
	}

	// -------------------------------------------------------------------------
	// Utility
	// -------------------------------------------------------------------------

	/**
	 * Count the leading whitespace characters of a line.
	 */
	private function getIndent( string $line ): int {
		return strlen( $line ) - strlen( ltrim( $line ) );
	}
}

    /**
     * The whole catalogue, shape-compatible with the router.
     *
     * @return array<string, array{label: string, tools: array<int, string>}>
     */
    public static function presets(): array
    {
        return self::PRESETS;
    }

    /**
     * Tool slugs in one preset family.
     *
     * @return array<int, string>
     */
    public static function toolsFor(string $preset): array
    {
        return self::PRESETS[ $preset ]['tools'] ?? array();
    }

    /**
     * Tool slug to the families it belongs to.
     *
     * Built once per process: the router would otherwise rebuild it on every
     * ranked turn, and the membership never changes at runtime.
     *
     * @return array<string, array<int, string>>
     */
    public static function index(): array
    {
        static $index = null;

        return $index ??= ToolRouterHarness::buildPresetIndex(self::PRESETS);
    }

    public static function has(string $preset): bool
    {
        return isset(self::PRESETS[ $preset ]);
    }
